function A = xylem_isotope_attribution_two_pool_exactD( ...
    t, ...
    rRoot, ...
    E, ...
    storageLumenAmount, ...
    storageLivingAmount, ...
    JreleaseLumen, ...
    JrechargeLumen, ...
    JreleaseLiving, ...
    JrechargeLiving, ...
    storageWeights, ...
    mobileWaterSegment, ...
    tauLumen, ...
    tauLiving, ...
    rLumen0, ...
    rLiving0, ...
    nMobile, ...
    dtForcing, ...
    rootIsotopeInterpolation, ...
    secondsPerDay, ...
    Rstandard_DH, ...
    odeRelTol, ...
    odeAbsTol, ...
    odeMaxStepFraction, ...
    throughflowTolerance_mol_m2_s)
%XYLEM_ISOTOPE_ATTRIBUTION_TWO_POOL_EXACTD
%
% Exact-D, interval-wise two-pool xylem isotope attribution.
%
% Counterfactuals separate:
%   1. mobile transport
%   2. fixed-storage gross exchange
%   3. dynamic storage-state modulation
%   4. explicit hydraulic storage routing
%
% Isotope state variables are exact D-atom inventories:
%
%   ND = 2 * W * xD
%
% with xD = R/(1+R).  All transfers are nonfractionating in the current
% validated xylem implementation.


%% ========================================================================
% Input preparation
% ========================================================================

t = ...
    t(:);

rRoot = ...
    rRoot(:);

E = ...
    E(:);

storageLumenAmount = ...
    storageLumenAmount(:);

storageLivingAmount = ...
    storageLivingAmount(:);

JreleaseLumen = ...
    JreleaseLumen(:);

JrechargeLumen = ...
    JrechargeLumen(:);

JreleaseLiving = ...
    JreleaseLiving(:);

JrechargeLiving = ...
    JrechargeLiving(:);

storageWeights = ...
    storageWeights(:);

nT = ...
    numel(t);


if ...
        numel(rRoot) ~= nT ...
        || numel(E) ~= nT ...
        || numel(storageLumenAmount) ~= nT ...
        || numel(storageLivingAmount) ~= nT ...
        || numel(JreleaseLumen) ~= nT ...
        || numel(JrechargeLumen) ~= nT ...
        || numel(JreleaseLiving) ~= nT ...
        || numel(JrechargeLiving) ~= nT

    error( ...
        'Exact-D attribution forcing arrays must match time length.');

end


if numel(storageWeights) ~= nMobile

    error( ...
        'storageWeights must match nMobile.');

end


if abs(sum(storageWeights)-1) > 1e-10

    error( ...
        'storageWeights must sum to one.');

end


if nargin < 17 || isempty(dtForcing)

    dtForcing = ...
        min(diff(t));

end


if nargin < 25 || isempty(throughflowTolerance_mol_m2_s)

    throughflowTolerance_mol_m2_s = ...
        1e-8;

end

throughflowTolerance_mol_m2_day = ...
    throughflowTolerance_mol_m2_s ...
    .* secondsPerDay;


%% ========================================================================
% Scenario 0: mobile transport only
% ========================================================================

cfg = ...
    baseConfig();

A.rNoStorage = ...
    runScenario(cfg);


%% ========================================================================
% Fixed-storage gross exchange
% ========================================================================

cfg = ...
    baseConfig();

cfg.exchangeLumen = ...
    true;

A.rGrossLumenOnlyFixed = ...
    runScenario(cfg);


cfg = ...
    baseConfig();

cfg.exchangeLiving = ...
    true;

A.rGrossLivingOnlyFixed = ...
    runScenario(cfg);


cfg = ...
    baseConfig();

cfg.exchangeLumen = ...
    true;

cfg.exchangeLiving = ...
    true;

A.rGrossBothFixed = ...
    runScenario(cfg);


%% ========================================================================
% Dynamic storage-state modulation
% ========================================================================

cfg = ...
    baseConfig();

cfg.exchangeLumen = ...
    true;

cfg.exchangeLiving = ...
    true;

cfg.dynamicLumen = ...
    true;

A.rStateLumenDynamic = ...
    runScenario(cfg);


cfg = ...
    baseConfig();

cfg.exchangeLumen = ...
    true;

cfg.exchangeLiving = ...
    true;

cfg.dynamicLiving = ...
    true;

A.rStateLivingDynamic = ...
    runScenario(cfg);


cfg = ...
    baseConfig();

cfg.exchangeLumen = ...
    true;

cfg.exchangeLiving = ...
    true;

cfg.dynamicLumen = ...
    true;

cfg.dynamicLiving = ...
    true;

A.rStateBothDynamic = ...
    runScenario(cfg);


%% ========================================================================
% Selective hydraulic routing
% ========================================================================

cfg = ...
    baseConfig();

cfg.exchangeLumen = ...
    true;

cfg.exchangeLiving = ...
    true;

cfg.dynamicLumen = ...
    true;

cfg.dynamicLiving = ...
    true;

cfg.hydraulicLumen = ...
    true;

A.rHydraulicLumenOnly = ...
    runScenario(cfg);


cfg = ...
    baseConfig();

cfg.exchangeLumen = ...
    true;

cfg.exchangeLiving = ...
    true;

cfg.dynamicLumen = ...
    true;

cfg.dynamicLiving = ...
    true;

cfg.hydraulicLiving = ...
    true;

A.rHydraulicLivingOnly = ...
    runScenario(cfg);


%% ========================================================================
% Metadata
% ========================================================================

A.inventoryConvention = ...
    'exact D atoms: ND = 2*W*xD';

A.integrationConvention = ...
    'interval-wise; hydraulic rates use ending node';

A.Rstandard_DH = ...
    Rstandard_DH;


%% ========================================================================
% Nested scenario runner
% ========================================================================

    function rDelivered = runScenario(cfg)

        SL0 = ...
            storageWeights ...
            .* storageLumenAmount(1);

        SE0 = ...
            storageWeights ...
            .* storageLivingAmount(1);


        xMobile0 = ...
            normalizedRatioToAtomFractionLocal( ...
                rRoot(1), ...
                Rstandard_DH);

        xLumen0 = ...
            normalizedRatioToAtomFractionLocal( ...
                rLumen0, ...
                Rstandard_DH);

        xLiving0 = ...
            normalizedRatioToAtomFractionLocal( ...
                rLiving0, ...
                Rstandard_DH);


        NDm0 = ...
            2 ...
            .* mobileWaterSegment ...
            .* repmat( ...
                xMobile0, ...
                nMobile, ...
                1);

        NDL0 = ...
            2 ...
            .* SL0 ...
            .* xLumen0;

        NDE0 = ...
            2 ...
            .* SE0 ...
            .* xLiving0;


        y0 = [ ...
            NDm0; ...
            NDL0; ...
            NDE0];


        Y = ...
            NaN(nT,numel(y0));

        Y(1,:) = ...
            y0.';


        for kk = 1:nT-1

            interval = ...
                struct;

            interval.t0 = ...
                t(kk);

            interval.t1 = ...
                t(kk+1);

            interval.rRoot0 = ...
                rRoot(kk);

            interval.rRoot1 = ...
                rRoot(kk+1);

            interval.Eday = ...
                max(E(kk+1),0) ...
                .* secondsPerDay;

            interval.JLrelActualDay = ...
                max(JreleaseLumen(kk+1),0) ...
                .* secondsPerDay;

            interval.JLrechActualDay = ...
                max(JrechargeLumen(kk+1),0) ...
                .* secondsPerDay;

            interval.JErelActualDay = ...
                max(JreleaseLiving(kk+1),0) ...
                .* secondsPerDay;

            interval.JErechActualDay = ...
                max(JrechargeLiving(kk+1),0) ...
                .* secondsPerDay;

            interval.SLstart = ...
                storageLumenAmount(kk);

            interval.SLend = ...
                storageLumenAmount(kk+1);

            interval.SEstart = ...
                storageLivingAmount(kk);

            interval.SEend = ...
                storageLivingAmount(kk+1);


            dtInterval = ...
                interval.t1 ...
                - interval.t0;


            opts = ...
                odeset( ...
                    'RelTol',odeRelTol, ...
                    'AbsTol',odeAbsTol, ...
                    'MaxStep', ...
                    dtInterval ...
                    .* odeMaxStepFraction);


            rhs = ...
                @(tt,y) scenarioRHSInterval( ...
                    tt, ...
                    y, ...
                    interval, ...
                    cfg);


            [~,Yi] = ...
                ode15s( ...
                    rhs, ...
                    [interval.t0 interval.t1], ...
                    Y(kk,:).', ...
                    opts);


            Y(kk+1,:) = ...
                Yi(end,:);

        end


        NDm = ...
            Y(:,1:nMobile);


        Wmobile = ...
            mobileWaterSegment ...
            .* ones(nT,nMobile);


        Rm = ...
            exactDInventoryToNormalizedRatioLocal( ...
                NDm, ...
                Wmobile, ...
                Rstandard_DH);


        rDelivered = ...
            Rm(:,end);

    end


%% ========================================================================
% Nested exact-D interval RHS
% ========================================================================

    function dydt = scenarioRHSInterval( ...
            tt, ...
            y, ...
            interval, ...
            cfg)

        NDm = ...
            y(1:nMobile);

        NDL = ...
            y( ...
                nMobile+1 : 2*nMobile);

        NDE = ...
            y( ...
                2*nMobile+1 : 3*nMobile);


        if interval.t1 > interval.t0

            f = ...
                (tt - interval.t0) ...
                ./ (interval.t1 - interval.t0);

        else

            f = ...
                1;

        end


        f = ...
            min(max(f,0),1);


        if rootIsotopeInterpolation == "next"

            rIn = ...
                interval.rRoot1;

        else

            rIn = ...
                interval.rRoot0 ...
                + f ...
                .* ( ...
                    interval.rRoot1 ...
                    - interval.rRoot0);

        end


        xIn = ...
            normalizedRatioToAtomFractionLocal( ...
                rIn, ...
                Rstandard_DH);


        Et = ...
            interval.Eday;


        if Et < -throughflowTolerance_mol_m2_day

            error( ...
                'Attribution terminal throughflow is materially negative.');

        end


        Et = ...
            max(Et,0);


        JLrelActual = ...
            interval.JLrelActualDay;

        JLrechActual = ...
            interval.JLrechActualDay;

        JErelActual = ...
            interval.JErelActualDay;

        JErechActual = ...
            interval.JErechActualDay;


        if cfg.dynamicLumen

            SLtotal = ...
                interval.SLstart ...
                + f ...
                .* ( ...
                    interval.SLend ...
                    - interval.SLstart);

        else

            SLtotal = ...
                storageLumenAmount(1);

        end


        if cfg.dynamicLiving

            SEtotal = ...
                interval.SEstart ...
                + f ...
                .* ( ...
                    interval.SEend ...
                    - interval.SEstart);

        else

            SEtotal = ...
                storageLivingAmount(1);

        end


        SLtotal = ...
            max(SLtotal,0);

        SEtotal = ...
            max(SEtotal,0);


        SL = ...
            storageWeights ...
            .* SLtotal;

        SE = ...
            storageWeights ...
            .* SEtotal;


        if cfg.hydraulicLumen

            JLrelTotal = ...
                JLrelActual;

            JLrechTotal = ...
                JLrechActual;

        else

            JLrelTotal = ...
                0;

            JLrechTotal = ...
                0;

        end


        if cfg.hydraulicLiving

            JErelTotal = ...
                JErelActual;

            JErechTotal = ...
                JErechActual;

        else

            JErelTotal = ...
                0;

            JErechTotal = ...
                0;

        end


        JLrel = ...
            storageWeights ...
            .* JLrelTotal;

        JLrech = ...
            storageWeights ...
            .* JLrechTotal;

        JErel = ...
            storageWeights ...
            .* JErelTotal;

        JErech = ...
            storageWeights ...
            .* JErechTotal;


        JLneutralTotal = ...
            0;

        JEneutralTotal = ...
            0;


        if ...
                cfg.dynamicLumen ...
                && ~cfg.hydraulicLumen

            JLneutralTotal = ...
                JLrechActual ...
                - JLrelActual;

        end


        if ...
                cfg.dynamicLiving ...
                && ~cfg.hydraulicLiving

            JEneutralTotal = ...
                JErechActual ...
                - JErelActual;

        end


        JLneutral = ...
            storageWeights ...
            .* JLneutralTotal;

        JEneutral = ...
            storageWeights ...
            .* JEneutralTotal;


        if cfg.exchangeLumen

            JexchangeL = ...
                SL ...
                ./ tauLumen;

        else

            JexchangeL = ...
                zeros(nMobile,1);

        end


        if cfg.exchangeLiving

            JexchangeE = ...
                SE ...
                ./ tauLiving;

        else

            JexchangeE = ...
                zeros(nMobile,1);

        end


        xM = ...
            NDm ...
            ./ (2 .* mobileWaterSegment);


        xL = ...
            xM;

        xE = ...
            xM;


        storageTol = ...
            1e-12;

        validL = ...
            SL > storageTol;

        validE = ...
            SE > storageTol;


        xL(validL) = ...
            NDL(validL) ...
            ./ (2 .* SL(validL));

        xE(validE) = ...
            NDE(validE) ...
            ./ (2 .* SE(validE));


        Jr = ...
            Et ...
            - (JLrelTotal - JLrechTotal) ...
            - (JErelTotal - JErechTotal);


        if Jr < -throughflowTolerance_mol_m2_day

            error( ...
                ['Selective exact-D attribution produced materially ' ...
                 'negative root inflow at t = %.12g d: ' ...
                 '%.12g mol m^-2 day^-1.'], ...
                tt, ...
                Jr);

        end


        Jr = ...
            max(Jr,0);


        Jin = ...
            zeros(nMobile,1);

        Jout = ...
            zeros(nMobile,1);

        Jin(1) = ...
            Jr;


        for j = 1:nMobile

            Jout(j) = ...
                Jin(j) ...
                + JLrel(j) ...
                + JErel(j) ...
                - JLrech(j) ...
                - JErech(j);


            if Jout(j) < -throughflowTolerance_mol_m2_day

                error( ...
                    ['Materially negative mobile flow in exact-D ' ...
                     'attribution at t = %.12g d, segment %d.'], ...
                    tt, ...
                    j);

            end


            Jout(j) = ...
                max(Jout(j),0);


            if j < nMobile

                Jin(j+1) = ...
                    Jout(j);

            end

        end


        dNDm = ...
            zeros(nMobile,1);

        dNDL = ...
            zeros(nMobile,1);

        dNDE = ...
            zeros(nMobile,1);


        for j = 1:nMobile

            if j == 1

                xUpstream = ...
                    xIn;

            else

                xUpstream = ...
                    xM(j-1);

            end


            dNDm(j) = ...
                2 ...
                .* ( ...
                    Jin(j) .* xUpstream ...
                    + (JexchangeL(j) + JLrel(j)) .* xL(j) ...
                    + (JexchangeE(j) + JErel(j)) .* xE(j) ...
                    - ( ...
                        Jout(j) ...
                        + JLrech(j) ...
                        + JErech(j) ...
                        + JexchangeL(j) ...
                        + JexchangeE(j)) .* xM(j));


            dNDL(j) = ...
                2 ...
                .* ( ...
                    JLrech(j) .* xM(j) ...
                    - JLrel(j) .* xL(j) ...
                    + JexchangeL(j) .* (xM(j)-xL(j)) ...
                    + JLneutral(j) .* xL(j));


            dNDE(j) = ...
                2 ...
                .* ( ...
                    JErech(j) .* xM(j) ...
                    - JErel(j) .* xE(j) ...
                    + JexchangeE(j) .* (xM(j)-xE(j)) ...
                    + JEneutral(j) .* xE(j));

        end


        dydt = [ ...
            dNDm; ...
            dNDL; ...
            dNDE];

    end


%% ========================================================================
% Base configuration
% ========================================================================

    function cfg = baseConfig()

        cfg.exchangeLumen = ...
            false;

        cfg.exchangeLiving = ...
            false;

        cfg.dynamicLumen = ...
            false;

        cfg.dynamicLiving = ...
            false;

        cfg.hydraulicLumen = ...
            false;

        cfg.hydraulicLiving = ...
            false;

    end

end


%% =========================================================================
function x = normalizedRatioToAtomFractionLocal(r,Rstd)

R = ...
    Rstd ...
    .* r;

x = ...
    R ...
    ./ (1 + R);

end


%% =========================================================================
function r = exactDInventoryToNormalizedRatioLocal(ND,W,Rstd)

x = ...
    ND ...
    ./ (2 .* W);

if any(~isfinite(x),'all')

    error( ...
        'Nonfinite D atom fraction in exact-D attribution.');

end


if any(x <= -1e-12 | x >= 1+1e-12,'all')

    error( ...
        'Invalid D atom fraction in exact-D attribution.');

end


x = ...
    min(max(x,0),1-eps);

R = ...
    x ...
    ./ (1-x);

r = ...
    R ...
    ./ Rstd;

end
