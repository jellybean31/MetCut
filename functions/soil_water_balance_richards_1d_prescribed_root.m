function S = ...
    soil_water_balance_richards_1d_prescribed_root( ...
        timeDays, ...
        precip_mm_day, ...
        JrootGround_mol_m2_s, ...
        psiInitial_MPa, ...
        soilHydro, ...
        G, ...
        cfg)
%SOIL_WATER_BALANCE_RICHARDS_1D_PRESCRIBED_ROOT
%
% Mass-conservative 1-D mixed-form Richards solver on an arbitrary
% finite-volume grid.
%
% Coordinate:
%
%   z positive downward.
%
% Darcy flux:
%
%   q = K * (1 - dh/dz)
%
% where q > 0 is downward.
%
% Root flux:
%
%   Jroot > 0 : soil -> root uptake
%   Jroot < 0 : root -> soil release
%
% This implementation includes:
%
%   - vertically resolved Richards flow
%   - van Genuchten-Mualem hydraulic properties
%   - prescribed cell-specific root uptake/release
%   - rainfall atmospheric boundary
%   - automatic ponding/runoff boundary switching
%   - free-drainage lower boundary
%   - modified Picard nonlinear iteration
%   - adaptive internal substepping
%   - finite-volume mass-balance diagnostics


%% ========================================================================
% Constants
% ========================================================================

rhoWater = ...
    1000;

g = ...
    9.81;

molarMassWater_kg_mol = ...
    18.01528e-3;

Cw = ...
    rhoWater ...
    ./ molarMassWater_kg_mol;

secondsPerDay = ...
    86400;

headPerMPa = ...
    1e6 ...
    ./ (rhoWater .* g);


%% ========================================================================
% Configuration
% ========================================================================

if nargin < 7 || isempty(cfg)

    cfg = ...
        struct;

end


cfg = ...
    setDefault( ...
        cfg, ...
        'maxSubstep_s', ...
        300);

cfg = ...
    setDefault( ...
        cfg, ...
        'minSubstep_s', ...
        2);

cfg = ...
    setDefault( ...
        cfg, ...
        'maxPicardIterations', ...
        60);

cfg = ...
    setDefault( ...
        cfg, ...
        'headTolerance_m', ...
        1e-8);

cfg = ...
    setDefault( ...
        cfg, ...
        'cellMassTolerance_m', ...
        1e-10);

cfg = ...
    setDefault( ...
        cfg, ...
        'picardRelaxation', ...
        1.0);

cfg = ...
    setDefault( ...
        cfg, ...
        'capacityFloor_per_m', ...
        1e-10);

cfg = ...
    setDefault( ...
        cfg, ...
        'pondingHeadTolerance_m', ...
        1e-10);


%% ========================================================================
% Grid
% ========================================================================

dz = ...
    G.dz_m(:);

zCenter = ...
    G.zCenter_m(:);

zoneIndex = ...
    G.zoneIndex(:);

nCell = ...
    numel(dz);


if ...
        numel(zCenter) ~= nCell ...
        || numel(zoneIndex) ~= nCell

    error( ...
        'Grid geometry has inconsistent dimensions.');

end


%% ========================================================================
% Time
% ========================================================================

tDays = ...
    timeDays(:).';

nT = ...
    numel(tDays);

nInt = ...
    nT - 1;


if nT < 2

    error( ...
        'timeDays must contain at least two states.');

end


if any(diff(tDays) <= 0)

    error( ...
        'timeDays must be strictly increasing.');

end


dtCoarse_s = ...
    diff(tDays) ...
    .* secondsPerDay;


%% ========================================================================
% Atmospheric forcing
%
% Convention:
%
% precip_mm_day(k) applies over [t(k),t(k+1)).
% ========================================================================

precip = ...
    precip_mm_day(:).';


if numel(precip) == nInt

    precipInterval = ...
        precip;

elseif numel(precip) == nT

    precipInterval = ...
        precip(1:nInt);

else

    error( ...
        'precip_mm_day must contain nT or nT-1 values.');

end


if any(~isfinite(precipInterval)) || any(precipInterval < 0)

    error( ...
        'Precipitation must contain finite nonnegative values.');

end


qRainPotential_m_s = ...
    precipInterval ...
    ./ 1000 ...
    ./ secondsPerDay;


%% ========================================================================
% Root flux
% ========================================================================

JrootInput = ...
    JrootGround_mol_m2_s;


if isvector(JrootInput) && nCell == 1

    JrootInput = ...
        reshape(JrootInput,1,[]);

end


if size(JrootInput,1) ~= nCell

    error( ...
        ['JrootGround_mol_m2_s must contain one row per ' ...
         'Richards soil cell.']);

end


if size(JrootInput,2) == nT

    JrootInterval = ...
        JrootInput(:,1:nInt);

elseif size(JrootInput,2) == nInt

    JrootInterval = ...
        JrootInput;

else

    error( ...
        ['JrootGround_mol_m2_s must contain nT or nT-1 ' ...
         'columns.']);

end


if any(~isfinite(JrootInterval),'all')

    error( ...
        'Root flux contains nonfinite values.');

end


qRootInterval_m_s = ...
    JrootInterval ...
    ./ Cw;


%% ========================================================================
% Soil parameters
% ========================================================================

thetaR = ...
    expandCellParameter( ...
        soilHydro.thetaR, ...
        nCell, ...
        'thetaR');

thetaS = ...
    expandCellParameter( ...
        soilHydro.thetaS, ...
        nCell, ...
        'thetaS');

alphaMPa = ...
    expandCellParameter( ...
        soilHydro.alphaMPa, ...
        nCell, ...
        'alphaMPa');

nVG = ...
    expandCellParameter( ...
        soilHydro.n, ...
        nCell, ...
        'n');

Ksat = ...
    expandCellParameter( ...
        soilHydro.Ksat_m_s, ...
        nCell, ...
        'Ksat_m_s');


if isfield(soilHydro,'m')

    mVG = ...
        expandCellParameter( ...
            soilHydro.m, ...
            nCell, ...
            'm');

else

    mVG = ...
        1 ...
        - 1 ./ nVG;

end


if isfield(soilHydro,'l')

    lVG = ...
        expandCellParameter( ...
            soilHydro.l, ...
            nCell, ...
            'l');

else

    lVG = ...
        0.5 ...
        .* ones(nCell,1);

end


%% ========================================================================
% Initial condition
% ========================================================================

psiInitial = ...
    psiInitial_MPa(:);


if numel(psiInitial) ~= nCell

    error( ...
        'psiInitial_MPa must contain one value per soil cell.');

end


h = ...
    psiInitial ...
    .* headPerMPa;


[theta0,K0,~] = ...
    constitutiveState(h);


%% ========================================================================
% Output allocation
% ========================================================================

theta = ...
    NaN(nCell,nT);

psiMPa = ...
    NaN(nCell,nT);

Kunsat = ...
    NaN(nCell,nT);

waterAmount = ...
    NaN(nCell,nT);


theta(:,1) = ...
    theta0;

psiMPa(:,1) = ...
    psiInitial;

Kunsat(:,1) = ...
    K0;

waterAmount(:,1) = ...
    theta0 ...
    .* dz ...
    .* Cw;


JprecipPotential = ...
    NaN(1,nInt);

JinfiltrationActual = ...
    NaN(1,nInt);

Jrunoff = ...
    NaN(1,nInt);

Jdeep = ...
    NaN(1,nInt);

JrootSigned = ...
    JrootInterval;


stepMassResidual = ...
    NaN(1,nInt);

cumulativeMassResidual = ...
    NaN(1,nInt);

pondedInterval = ...
    false(1,nInt);

nAcceptedSubsteps = ...
    zeros(1,nInt);

maxPicardIterationsUsed = ...
    zeros(1,nInt);

minimumAcceptedSubstep_s = ...
    NaN(1,nInt);


%% ========================================================================
% Time integration
% ========================================================================

cumulativeResidual = ...
    0;


for k = 1:nInt

    dtTarget = ...
        dtCoarse_s(k);

    timeTolerance_s = ...
        max( ...
        1e-9, ...
        100 .* eps(dtTarget));


    qRain = ...
        qRainPotential_m_s(k);


    qRoot = ...
        qRootInterval_m_s(:,k);


    hStart = ...
        h;


    thetaStart = ...
        theta(:,k);

    %% Current state at the beginning of the first internal substep.
 

    thetaSubstepOld = ...
        theta(:,k);


    remaining_s = ...
        dtTarget;


    dtTry = ...
        min( ...
            cfg.maxSubstep_s, ...
            remaining_s);


    integratedTop_m = ...
        0;

    integratedRunoff_m = ...
        0;

    integratedDeep_m = ...
        0;

    integratedRoot_m = ...
        zeros(nCell,1);


    acceptedCount = ...
        0;

    maxIterationsThisInterval = ...
        0;

    minDtThisInterval = ...
        Inf;

    anyPonding = ...
        false;


    while remaining_s > timeTolerance_s

        dtTry = ...
            min( ...
                dtTry, ...
                remaining_s);

        %% ------------------------------------------------------------
        % First attempt: rainfall-flux upper boundary
        % ------------------------------------------------------------

        [trialFlux,okFlux] = ...
            solveSubstep( ...
            h, ...
            thetaSubstepOld, ...
            dtTry, ...
            qRain, ...
            qRoot, ...
            "flux");


        usePonding = ...
            false;


        if okFlux

            if ...
                    trialFlux.h(1) ...
                    > cfg.pondingHeadTolerance_m

                usePonding = ...
                    true;

            end

        end


        %% ------------------------------------------------------------
        % If rainfall-flux solution requires positive pressure head,
        % resolve with h(surface)=0 atmospheric boundary.
        % ------------------------------------------------------------

        if usePonding

            [trial,ok] = ...
                solveSubstep( ...
                h, ...
                thetaSubstepOld, ...
                dtTry, ...
                qRain, ...
                qRoot, ...
                "ponded");


            if ok

                qTopCapacity = ...
                    trial.qTop_m_s;


                % A ponded boundary should never admit more water than
                % the rainfall supply available during this substep.

                if qTopCapacity > qRain

                    [trial,ok] = ...
                        solveSubstep( ...
                        h, ...
                        thetaSubstepOld, ...
                        dtTry, ...
                        qRain, ...
                        qRoot, ...
                        "flux");

                    usePonding = ...
                        false;

                end

            end

        else

            trial = ...
                trialFlux;

            ok = ...
                okFlux;

        end


        %% ------------------------------------------------------------
        % Failed nonlinear solve -> halve timestep
        % ------------------------------------------------------------

        if ~ok

            dtTry = ...
                0.5 ...
                .* dtTry;


            if dtTry < cfg.minSubstep_s

                error([ ...
                    'RICHARDS_SUBSTEP_FAILURE\n' ...
                    'Coarse interval: %d\n' ...
                    'Time: %.9f d\n' ...
                    'Remaining interval: %.6f s\n' ...
                    'Attempted dt: %.6f s\n'], ...
                    k, ...
                    tDays(k), ...
                    remaining_s, ...
                    dtTry);

            end


            continue

        end


        %% ------------------------------------------------------------
        % Accepted substep
        % ------------------------------------------------------------

        h = ...
            trial.h;


        %% Advance the storage reference for the NEXT internal substep.

        thetaSubstepOld = ...
            trial.theta;


        acceptedCount = ...
            acceptedCount ...
            + 1;


        maxIterationsThisInterval = ...
            max( ...
                maxIterationsThisInterval, ...
                trial.nIterations);


        minDtThisInterval = ...
            min( ...
                minDtThisInterval, ...
                dtTry);


        anyPonding = ...
            anyPonding ...
            || usePonding;


        qTopActual = ...
            trial.qTop_m_s;


        qRunoff = ...
            max( ...
                qRain ...
                - qTopActual, ...
                0);


        integratedTop_m = ...
            integratedTop_m ...
            + qTopActual ...
            .* dtTry;


        integratedRunoff_m = ...
            integratedRunoff_m ...
            + qRunoff ...
            .* dtTry;


        integratedDeep_m = ...
            integratedDeep_m ...
            + trial.qBottom_m_s ...
            .* dtTry;


        integratedRoot_m = ...
            integratedRoot_m ...
            + qRoot ...
            .* dtTry;


        remaining_s = ...
            remaining_s ...
            - dtTry;


        if remaining_s <= timeTolerance_s

            remaining_s = ...
                0;

        end


        %% After a successful reduced step, cautiously grow again.

        dtTry = ...
            min( ...
                cfg.maxSubstep_s, ...
                1.5 ...
                .* dtTry);

    end


    %% ====================================================================
    % Store final node state
    % ====================================================================

    thetaEnd = ...
        thetaSubstepOld;


    [thetaCheck,Kend,~] = ...
        constitutiveState(h);


    thetaConsistencyResidual = ...
        max(abs( ...
        thetaCheck ...
        - thetaEnd));


    if thetaConsistencyResidual > 1e-12

        error( ...
            ['Richards theta/head state inconsistency: ' ...
            '%.12g'], ...
            thetaConsistencyResidual);

    end


    theta(:,k+1) = ...
        thetaEnd;


    psiMPa(:,k+1) = ...
        h ...
        ./ headPerMPa;


    Kunsat(:,k+1) = ...
        Kend;


    waterAmount(:,k+1) = ...
        thetaEnd ...
        .* dz ...
        .* Cw;


    %% ====================================================================
    % Interval-average fluxes
    % ====================================================================

    JprecipPotential(k) = ...
        qRain ...
        .* Cw;


    JinfiltrationActual(k) = ...
        integratedTop_m ...
        ./ dtTarget ...
        .* Cw;


    Jrunoff(k) = ...
        integratedRunoff_m ...
        ./ dtTarget ...
        .* Cw;


    Jdeep(k) = ...
        integratedDeep_m ...
        ./ dtTarget ...
        .* Cw;


    %% ====================================================================
    % Exact finite-volume mass balance
    % ====================================================================

    dStorage_mol_m2 = ...
        sum( ...
            ( ...
                thetaEnd ...
                - thetaStart) ...
            .* dz) ...
        .* Cw;


    predictedChange_mol_m2 = ...
        ( ...
            integratedTop_m ...
            - integratedDeep_m ...
            - sum(integratedRoot_m)) ...
        .* Cw;


    stepResidual = ...
        dStorage_mol_m2 ...
        - predictedChange_mol_m2;


    cumulativeResidual = ...
        cumulativeResidual ...
        + stepResidual;


    stepMassResidual(k) = ...
        stepResidual;


    cumulativeMassResidual(k) = ...
        cumulativeResidual;


    pondedInterval(k) = ...
        anyPonding;


    nAcceptedSubsteps(k) = ...
        acceptedCount;


    maxPicardIterationsUsed(k) = ...
        maxIterationsThisInterval;


    minimumAcceptedSubstep_s(k) = ...
        minDtThisInterval;

end


%% ========================================================================
% Outputs
% ========================================================================

S.timeDays = ...
    tDays;

S.zCenter_m = ...
    zCenter;

S.dz_m = ...
    dz;

S.zoneIndex = ...
    zoneIndex;

S.theta = ...
    theta;

S.psiMPa = ...
    psiMPa;

S.Kunsat_m_s = ...
    Kunsat;

S.waterAmount_mol_m2 = ...
    waterAmount;


S.JprecipPotential_mol_m2_s = ...
    JprecipPotential;

S.JinfiltrationActualInterval_mol_m2_s = ...
    JinfiltrationActual;

S.JrunoffTotalInterval_mol_m2_s = ...
    Jrunoff;

S.Jdeep_mol_m2_s = ...
    Jdeep;

S.JrootSignedInterval_mol_m2_s = ...
    JrootSigned;


S.stepMassBalanceResidual_mol_m2 = ...
    stepMassResidual;

S.cumulativeMassBalanceResidual_mol_m2 = ...
    cumulativeMassResidual;


S.pondedInterval = ...
    pondedInterval;

S.nAcceptedSubsteps = ...
    nAcceptedSubsteps;

S.maxPicardIterationsUsed = ...
    maxPicardIterationsUsed;

S.minimumAcceptedSubstep_s = ...
    minimumAcceptedSubstep_s;


S.config = ...
    cfg;


%% ========================================================================
% Nested nonlinear solver
% ========================================================================

    function [R,converged] = ...
            solveSubstep( ...
                hOld, ...
                thetaOldReference, ...
                dt_s, ...
                qRainBoundary, ...
                qRootCell, ...
                boundaryMode)

        hIter = ...
            hOld;


        converged = ...
            false;


        R = ...
            struct;


        qRootCell = ...
            qRootCell(:);


        for iteration = 1:cfg.maxPicardIterations

            [thetaIter,Kiter,Citer] = ...
                constitutiveState(hIter);


            [Kface,aFace] = ...
                internalInterfaceTerms( ...
                    Kiter);


            A = ...
                spalloc( ...
                    nCell, ...
                    nCell, ...
                    3*nCell);


            b = ...
                zeros(nCell,1);


            storageConstant = ...
                ( ...
                    thetaIter ...
                    - thetaOldReference ...
                    - Citer .* hIter) ...
                .* dz ...
                ./ dt_s;


            %% ------------------------------------------------------------
            % Top cell
            % ------------------------------------------------------------

            if boundaryMode == "flux"

                aDown = ...
                    aFace(1);


                KDown = ...
                    Kface(1);


                A(1,1) = ...
                    Citer(1) ...
                    .* dz(1) ...
                    ./ dt_s ...
                    + aDown;


                A(1,2) = ...
                    -aDown;


                b(1) = ...
                    qRainBoundary ...
                    - KDown ...
                    - qRootCell(1) ...
                    - storageConstant(1);


            elseif boundaryMode == "ponded"

                dTop = ...
                    0.5 ...
                    .* dz(1);


                KTop = ...
                    Kiter(1);


                aTop = ...
                    KTop ...
                    ./ dTop;


                aDown = ...
                    aFace(1);


                KDown = ...
                    Kface(1);


                A(1,1) = ...
                    Citer(1) ...
                    .* dz(1) ...
                    ./ dt_s ...
                    + aTop ...
                    + aDown;


                A(1,2) = ...
                    -aDown;


                b(1) = ...
                    KTop ...
                    - KDown ...
                    - qRootCell(1) ...
                    - storageConstant(1);


            else

                error( ...
                    'Unknown Richards upper-boundary mode.');

            end


            %% ------------------------------------------------------------
            % Interior cells
            % ------------------------------------------------------------

            for i = 2:nCell-1

                aUp = ...
                    aFace(i-1);


                aDown = ...
                    aFace(i);


                KUp = ...
                    Kface(i-1);


                KDown = ...
                    Kface(i);


                A(i,i-1) = ...
                    -aUp;


                A(i,i) = ...
                    Citer(i) ...
                    .* dz(i) ...
                    ./ dt_s ...
                    + aUp ...
                    + aDown;


                A(i,i+1) = ...
                    -aDown;


                b(i) = ...
                    KUp ...
                    - KDown ...
                    - qRootCell(i) ...
                    - storageConstant(i);

            end


            %% ------------------------------------------------------------
            % Bottom cell: free drainage
            %
            % q_bottom = K_bottom
            % ------------------------------------------------------------

            aUp = ...
                aFace(end);


            KUp = ...
                Kface(end);


            KBottom = ...
                Kiter(end);


            A(nCell,nCell-1) = ...
                -aUp;


            A(nCell,nCell) = ...
                Citer(end) ...
                .* dz(end) ...
                ./ dt_s ...
                + aUp;


            b(nCell) = ...
                KUp ...
                - KBottom ...
                - qRootCell(end) ...
                - storageConstant(end);


            %% ------------------------------------------------------------
            % Linear Picard solve
            % ------------------------------------------------------------

            hLinear = ...
                A ...
                \ b;


            if any(~isfinite(hLinear))

                break

            end


            hTrial = ...
                hIter ...
                + cfg.picardRelaxation ...
                .* ( ...
                    hLinear ...
                    - hIter);


            [thetaTrial,Ktrial,~] = ...
                constitutiveState(hTrial);


            %% ------------------------------------------------------------
            % Exact fluxes from trial state
            % ------------------------------------------------------------

            [qInterface,qTop,qBottom] = ...
                fluxesFromState( ...
                    hTrial, ...
                    Ktrial, ...
                    qRainBoundary, ...
                    boundaryMode);


            %% ------------------------------------------------------------
            % Cellwise exact mixed-form residual
            % ------------------------------------------------------------

            qIn = ...
                [ ...
                qTop; ...
                qInterface];


            qOut = ...
                [ ...
                qInterface; ...
                qBottom];


            cellMassResidual_m = ...
                ( ...
                    thetaTrial ...
                    - thetaOldReference) ...
                .* dz ...
                - dt_s ...
                .* ( ...
                    qIn ...
                    - qOut ...
                    - qRootCell);


            maxHeadChange = ...
                max( ...
                    abs( ...
                        hTrial ...
                        - hIter));


            maxMassResidual = ...
                max( ...
                    abs( ...
                        cellMassResidual_m));


            hIter = ...
                hTrial;


            if ...
                    maxHeadChange ...
                    <= cfg.headTolerance_m ...
                    && maxMassResidual ...
                    <= cfg.cellMassTolerance_m

                converged = ...
                    true;


                R.h = ...
                    hTrial;

                R.theta = ...
                    thetaTrial;

                R.K_m_s = ...
                    Ktrial;

                R.qInterface_m_s = ...
                    qInterface;

                R.qTop_m_s = ...
                    qTop;

                R.qBottom_m_s = ...
                    qBottom;

                R.cellMassResidual_m = ...
                    cellMassResidual_m;

                R.nIterations = ...
                    iteration;


                return

            end

        end


        R.h = ...
            hIter;

        R.nIterations = ...
            cfg.maxPicardIterations;

    end


%% ========================================================================
% Constitutive relations
% ========================================================================

    function [thetaValue,Kvalue,Cvalue] = ...
            constitutiveState(hValue)

        psi = ...
            hValue ...
            ./ headPerMPa;


        saturated = ...
            psi >= 0;


        x = ...
            alphaMPa ...
            .* max( ...
                -psi, ...
                0);


        Se = ...
            ( ...
                1 ...
                + x.^nVG ...
            ).^(-mVG);


        Se(saturated) = ...
            1;


        thetaValue = ...
            thetaR ...
            + ( ...
                thetaS ...
                - thetaR) ...
            .* Se;


        Krel = ...
            Se.^lVG ...
            .* ( ...
                1 ...
                - ( ...
                    1 ...
                    - Se.^(1 ./ mVG) ...
                  ).^mVG ...
               ).^2;


        Krel = ...
            min( ...
                max(Krel,0), ...
                1);


        Kvalue = ...
            Ksat ...
            .* Krel;


        %% ------------------------------------------------------------
        % C = dtheta / dh
        % ------------------------------------------------------------

        Cvalue = ...
            zeros(nCell,1);


        unsat = ...
            ~saturated;


        xu = ...
            x(unsat);


        dtheta_dpsi = ...
            ( ...
                thetaS(unsat) ...
                - thetaR(unsat)) ...
            .* mVG(unsat) ...
            .* nVG(unsat) ...
            .* alphaMPa(unsat) ...
            .* xu.^( ...
                nVG(unsat) ...
                - 1) ...
            .* ( ...
                1 ...
                + xu.^nVG(unsat) ...
               ).^( ...
                -mVG(unsat) ...
                - 1);


        Cvalue(unsat) = ...
            dtheta_dpsi ...
            ./ headPerMPa;


        Cvalue = ...
            max( ...
                Cvalue, ...
                cfg.capacityFloor_per_m);

    end


%% ========================================================================
% Internal interface conductivity
% ========================================================================

    function [Kface,aFace] = ...
            internalInterfaceTerms(Kcell)

        Kface = ...
            zeros(nCell-1,1);


        dCenter = ...
            diff(zCenter);


        for ii = 1:nCell-1

            K1 = ...
                Kcell(ii);


            K2 = ...
                Kcell(ii+1);


            if zoneIndex(ii) == zoneIndex(ii+1)

                % Same material:
                %
                % arithmetic mean is the conventional centered
                % modified-Picard approximation and avoids recreating
                % the coarse-grid wetting-front bottleneck.

                Kface(ii) = ...
                    0.5 ...
                    .* ( ...
                        K1 ...
                        + K2);

            else

                % True material/horizon boundary:
                %
                % use harmonic mean so a genuinely low-conductivity
                % horizon remains hydraulically restrictive.

                if K1 <= 0 || K2 <= 0

                    Kface(ii) = ...
                        0;

                else

                    Kface(ii) = ...
                        2 ...
                        .* K1 ...
                        .* K2 ...
                        ./ ( ...
                            K1 ...
                            + K2);

                end

            end

        end


        aFace = ...
            Kface ...
            ./ dCenter;

    end


%% ========================================================================
% Flux calculation
% ========================================================================

    function [qInterface,qTop,qBottom] = ...
            fluxesFromState( ...
                hState, ...
                Kcell, ...
                qRainBoundary, ...
                boundaryMode)

        [Kface,~] = ...
            internalInterfaceTerms(Kcell);


        dCenter = ...
            diff(zCenter);


        qInterface = ...
            Kface ...
            .* ( ...
                1 ...
                - diff(hState) ...
                ./ dCenter);


        if boundaryMode == "flux"

            qTop = ...
                qRainBoundary;

        else

            dTop = ...
                0.5 ...
                .* dz(1);


            qTop = ...
                Kcell(1) ...
                .* ( ...
