function x = expandCellParameter(x,nCell,name)

x = ...
    x(:);


if isscalar(x)

    x = ...
        repmat( ...
            x, ...
            nCell, ...
            1);

end


if numel(x) ~= nCell

    error( ...
        '%s must be scalar or contain one value per soil cell.', ...
        name);

end

end