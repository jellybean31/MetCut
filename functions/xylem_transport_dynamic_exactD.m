function X = xylem_transport_dynamic_exactD( ...
    timeDays, deltaDRoot, hydro, plantState, traits)
%XYLEM_TRANSPORT_DYNAMIC_EXACTD
%
% Dynamic xylem isotope transport with:
%
%   1. exact D-atom mass conservation (ND = 2*W*xD)
%   2. interval-wise integration at hydraulic forcing boundaries
%   3. tanks-in-series mobile advection
%   4. gross mobile <-> storage exchange
%   5. hydraulic storage release/recharge
%   6. dynamic water-age tracking
%
%
% Hydraulic water balance:
%
%   Jroot + Jrelease - Jrecharge = JxylemToLeaf
%
% where JxylemToLeaf is the actual terminal xylem outflow.
%
% With leaf hydraulic capacitance:
%
%   JxylemToLeaf ~= E
%
% because:
%
%   JxylemToLeaf - E = dSleaf/dt
%
% Gross exchange is separate:
%
%   Jexchange
%
% represents bidirectional turnover that can occur even when net
% hydraulic storage change is zero.
%
%
% Positive hydraulic flux conventions:
%
%   JstorageRelease:
%       storage -> mobile xylem
%
%   JstorageRecharge:
%       mobile xylem -> storage
%
%
% The hydraulic storage flux is distributed among xylem storage
% compartments according to storageDistributionWeights.
%
% By default all compartments receive equal fractions.


%% ========================================================================
% Input preparation
% ========================================================================

t = ...
    timeDays(:);

dRoot = ...
    deltaDRoot(:);

nT = ...
    numel(t);


if numel(dRoot) ~= nT

    error( ...
        'deltaDRoot must have the same length as timeDays.');

end


if any(diff(t) <= 0)

    error( ...
        'timeDays must be strictly increasing.');

end

if isfield(traits,'rootIsotopeInterpolation')

    rootIsotopeInterpolation = ...
        lower(string( ...
            traits.rootIsotopeInterpolation));

else

    rootIsotopeInterpolation = ...
        "linear";

end


if ...
        rootIsotopeInterpolation ~= "linear" ...
        && rootIsotopeInterpolation ~= "next"

    error([ ...
        'traits.rootIsotopeInterpolation must be ' ...
        '"linear" or "next".']);

end


secondsPerDay = ...
    86400;

rhoWaterMol_m3 = ...
    55500;


%% ========================================================================
% Exact hydrogen-isotope inventory convention
%
% The transported isotope state is the exact number of moles of D atoms:
%
%   ND = 2 * W * xD
%
% where W is mol H2O and xD = R/(1+R).
% ========================================================================

if isfield(traits,'Rstandard_DH')

    Rstandard_DH = ...
        traits.Rstandard_DH;

else

    Rstandard_DH = ...
        155.76e-6;

end


if ...
        ~isscalar(Rstandard_DH) ...
        || ~isfinite(Rstandard_DH) ...
        || Rstandard_DH <= 0

    error( ...
        'traits.Rstandard_DH must be a positive finite scalar.');

end


%% ========================================================================
% Xylem ODE numerical controls
% ========================================================================

if isfield(traits,'odeRelTol')

    odeRelTol = ...
        traits.odeRelTol;

else

    odeRelTol = ...
        1e-8;

end


if isfield(traits,'odeAbsTol')

    odeAbsTol = ...
        traits.odeAbsTol;

else

    odeAbsTol = ...
        1e-10;

end


if isfield(traits,'odeMaxStepFraction')

    odeMaxStepFraction = ...
        traits.odeMaxStepFraction;

else

    odeMaxStepFraction = ...
        1.0;

end


if ...
        ~isscalar(odeRelTol) ...
        || ~isfinite(odeRelTol) ...
        || odeRelTol <= 0 ...
        || ~isscalar(odeAbsTol) ...
        || ~isfinite(odeAbsTol) ...
        || odeAbsTol <= 0 ...
        || ~isscalar(odeMaxStepFraction) ...
        || ~isfinite(odeMaxStepFraction) ...
        || odeMaxStepFraction <= 0 ...
        || odeMaxStepFraction > 1

    error( ...
        'Invalid xylem ODE numerical controls.');

end

%% ========================================================================
% Xylem isotope-selectivity interface
%
% Current validated xylem transport is nonfractionating.
%
% These hooks establish the interface for future true isotope-selective
% transfer without altering the present routing/mixing equations.
% ========================================================================

alpha = ...
    parse_xylem_isotope_selectivity( ...
        traits);

%% ========================================================================
% Hydraulic fluxes
%
% The terminal xylem flux is the actual water delivery from xylem
% into the leaf:
%
%   Jroot + JstorageRelease - JstorageRecharge
%       =
%   JxylemToLeaf
%
% Atmospheric transpiration E is retained separately as a diagnostic.
% With leaf capacitance:
%
%   JxylemToLeaf - E = dSleaf/dt
% ========================================================================

E = ...
    hydro.E(:);


%% ========================================================================
%  terminal xylem outflow
%
% Parallel leaf hydraulics:
%
%   terminal mobile xylem -> apoplast
%
%       Jterminal = JXA
%
% Legacy leaf hydraulics:
%
%   terminal mobile xylem -> lumped leaf
%
%       Jterminal = JxylemToLeaf
% ========================================================================

parallelLeafHydraulics = ...
    isfield(hydro,'leafParallelHydraulicsEnabled') ...
    && logical(hydro.leafParallelHydraulicsEnabled);


if ...
        parallelLeafHydraulics ...
        && isfield(hydro,'JxylemToApoplast')

    Jleaf = ...
        hydro.JxylemToApoplast(:);


    terminalFlowSource = ...
        "JxylemToApoplast";


elseif isfield(hydro,'JxylemToLeaf')

    Jleaf = ...
        hydro.JxylemToLeaf(:);


    terminalFlowSource = ...
        "JxylemToLeaf";


elseif isfield(hydro,'Jleaf')

    Jleaf = ...
        hydro.Jleaf(:);


    terminalFlowSource = ...
        "Jleaf";


else

    % Legacy zero-storage fallback only.

    Jleaf = ...
        E;


    terminalFlowSource = ...
        "E fallback";

end

%% ------------------------------------------------------------------------
% Hydraulic terminal-boundary consistency
% -------------------------------------------------------------------------

terminalAliasResidual = ...
    NaN(nT,1);


if ...
        parallelLeafHydraulics ...
        && isfield(hydro,'JxylemToApoplast') ...
        && isfield(hydro,'JxylemToLeaf')

    terminalAliasResidual = ...
        hydro.JxylemToApoplast(:) ...
        - hydro.JxylemToLeaf(:);


    if max(abs(terminalAliasResidual),[],'omitnan') > 1e-9

        error([ ...
            'hydro.JxylemToApoplast and hydro.JxylemToLeaf ' ...
            'are inconsistent.']);

    end

end


if isfield(hydro,'Jroot')

    Jroot = ...
        hydro.Jroot(:);

elseif isfield(hydro,'rootUptakeTotal')

    Jroot = ...
        hydro.rootUptakeTotal(:);

else

    Jroot = ...
        Jleaf;

end


if isfield(hydro,'JstorageRelease')

    Jrelease = ...
        hydro.JstorageRelease(:);

else

    Jrelease = ...
        zeros(nT,1);

end


if isfield(hydro,'JstorageRecharge')

    Jrecharge = ...
        hydro.JstorageRecharge(:);

else

    Jrecharge = ...
        zeros(nT,1);

end


if ...
        numel(E) ~= nT ...
        || numel(Jleaf) ~= nT ...
        || numel(Jroot) ~= nT ...
        || numel(Jrelease) ~= nT ...
        || numel(Jrecharge) ~= nT

    error([ ...
        'E, JxylemToLeaf, Jroot, JstorageRelease, and ' ...
        'JstorageRecharge must all match timeDays.']);

end


%% ------------------------------------------------------------------------
% Hydraulic throughflow sign consistency
% -------------------------------------------------------------------------

if isfield(traits,'throughflowTolerance_mol_m2_s')

    throughflowTolerance = ...
        traits.throughflowTolerance_mol_m2_s;

else

    throughflowTolerance = ...
        1e-8;

end


minE = ...
    min(E);

minJleaf = ...
    min(Jleaf);

minJroot = ...
    min(Jroot);


if ...
        minE < -throughflowTolerance ...
        || minJleaf < -throughflowTolerance ...
        || minJroot < -throughflowTolerance

    error([ ...
        'Hydraulic throughflow is materially negative. ' ...
        'Minimum values: E = %.15g, Jterminal = %.15g, ' ...
        'Jroot = %.15g mol m^-2 s^-1.'], ...
        minE, ...
        minJleaf, ...
        minJroot);

end

EhydraulicRaw = ...
    E;


JrootHydraulicRaw = Jroot;

X.JrootHydraulicRaw_mol_m2_s = ...
    JrootHydraulicRaw.';

% Clamp numerical zero-crossings
E(E < 0 & E >= -throughflowTolerance) = 0;
Jleaf(Jleaf < 0 & Jleaf >= -throughflowTolerance) = 0;
Jroot(Jroot < 0 & Jroot >= -throughflowTolerance) = 0;

X.Jroot_mol_m2_s = ...
    Jroot.';

X.JrootNumericalZeroAdjustment_mol_m2_s = ...
    (Jroot - JrootHydraulicRaw).';

%% ------------------------------------------------------------------------
% Component-specific hydraulic storage states and fluxes
% -------------------------------------------------------------------------

requiredHydroStorage = { ...
    'hydraulicStorageLumenAmount_mol_m2', ...
    'hydraulicStorageLivingAmount_mol_m2', ...
    'JstorageLumenRelease', ...
    'JstorageLumenRecharge', ...
    'JstorageLivingRelease', ...
    'JstorageLivingRecharge'};


for k = 1:numel(requiredHydroStorage)

    if ~isfield(hydro,requiredHydroStorage{k})

        error( ...
            'hydro.%s is required for two-pool xylem transport.', ...
            requiredHydroStorage{k});

    end

end


storageLumenAmount = ...
    hydro.hydraulicStorageLumenAmount_mol_m2(:);


storageLivingAmount = ...
    hydro.hydraulicStorageLivingAmount_mol_m2(:);


JreleaseLumen = ...
    hydro.JstorageLumenRelease(:);


JrechargeLumen = ...
    hydro.JstorageLumenRecharge(:);


JreleaseLiving = ...
    hydro.JstorageLivingRelease(:);


JrechargeLiving = ...
    hydro.JstorageLivingRecharge(:);


if ...
        numel(storageLumenAmount) ~= nT ...
        || numel(storageLivingAmount) ~= nT ...
        || numel(JreleaseLumen) ~= nT ...
        || numel(JrechargeLumen) ~= nT ...
        || numel(JreleaseLiving) ~= nT ...
        || numel(JrechargeLiving) ~= nT

    error( ...
        'Component hydraulic storage fields must match timeDays.');

end


if ...
        any(storageLumenAmount < 0) ...
        || any(storageLivingAmount < 0)

    error( ...
        'Component hydraulic storage amounts cannot be negative.');

end

%% ------------------------------------------------------------------------
% Hydraulic xylem-flow closure
%
% Jroot + Jrelease - Jrecharge = JxylemToLeaf
% -------------------------------------------------------------------------

flowClosure = ...
    Jroot ...
    + Jrelease ...
    - Jrecharge ...
    - Jleaf;


absoluteFlowClosureTolerance = ...
    max(2e-12,throughflowTolerance);


relativeFlowClosureTolerance = ...
    1e-6;


closureScale = ...
    max( ...
        [ ...
        abs(Jroot), ...
        abs(Jleaf), ...
        abs(Jrelease), ...
        abs(Jrecharge), ...
        repmat(1e-12,nT,1)], ...
        [], ...
        2);


relativeFlowClosure = ...
    abs(flowClosure) ...
    ./ closureScale;


badFlowClosure = ...
    abs(flowClosure) > absoluteFlowClosureTolerance ...
    & relativeFlowClosure > relativeFlowClosureTolerance;


if any(badFlowClosure)

    warning([ ...
        'Hydraulic root/storage/terminal-xylem fluxes do not ' ...
        'close within the combined absolute/relative tolerance. ' ...
        'Maximum absolute residual = %.12g mol m^-2 s^-1; ' ...
        'maximum relative residual among failing points = %.12g.'], ...
        max(abs(flowClosure(badFlowClosure))), ...
        max(relativeFlowClosure(badFlowClosure)));

end

leafStorageHydraulicFlux = ...
    Jleaf ...
    - E;


if isfield(hydro,'leafHydraulicStorageRate_mol_m2_s')

    leafStorageRateHydro = ...
        hydro.leafHydraulicStorageRate_mol_m2_s(:);


    if numel(leafStorageRateHydro) ~= nT

        error([ ...
            'hydro.leafHydraulicStorageRate_mol_m2_s must ' ...
            'match timeDays.']);

    end


    leafInterfaceClosure = ...
        Jleaf ...
        - E ...
        - leafStorageRateHydro;

else

    leafStorageRateHydro = ...
        NaN(nT,1);


    leafInterfaceClosure = ...
        NaN(nT,1);

end

%% ========================================================================
% Mobile-tank architecture
% ========================================================================

if ~isfield(traits,'nMobileTanks')

    error( ...
        'traits.nMobileTanks is required.');

end


nMobile = ...
    round(traits.nMobileTanks);


if ...
        ~isfinite(nMobile) ...
        || nMobile < 1

    error( ...
        'nMobileTanks must be an integer >= 1.');

end

if abs(nMobile - traits.nMobileTanks) > eps

    error( ...
        'nMobileTanks must be an integer.');

end


%% ========================================================================
% Reference flow
% ========================================================================

if isfield(traits,'referenceTranspiration_mol_m2_s')

    Jref = ...
        traits.referenceTranspiration_mol_m2_s;

else

    ii = ...
        find( ...
        isfinite(Jleaf) & Jleaf > 0, ...
        1,'first');

    if isempty(ii)

        error( ...
            'No positive reference water flux is available.');

    end

    Jref = ...
        Jleaf(ii);

end


JrefDay = ...
    Jref ...
    .* secondsPerDay;


%% ========================================================================
% Mobile-water amount
% ========================================================================

if ~isfield(traits,'mobileTransitDays')

    error( ...
        'traits.mobileTransitDays is required.');

end


mobileTransitDays = ...
    traits.mobileTransitDays;


if ...
        ~isfinite(mobileTransitDays) ...
        || mobileTransitDays <= 0

    error( ...
        'mobileTransitDays must be positive.');

end


if isfield(traits,'mobileWaterAmount_mol_m2')

    mobileWaterTotal = ...
        traits.mobileWaterAmount_mol_m2;

else

    mobileWaterTotal = ...
        JrefDay ...
        .* mobileTransitDays;

end


mobileWaterSegment = ...
    mobileWaterTotal ...
    ./ nMobile;



%% ========================================================================
% Hydraulic storage state
% ========================================================================

if ~isfield(hydro,'hydraulicStorageInitial_mol_m2')

    error([ ...
        'hydro.hydraulicStorageInitial_mol_m2 is required. ' ...
        'Hydraulic storage must be initialized in ' ...
        'solve_plant_hydraulics.']);

end


hydraulicStorageInitial = ...
    hydro.hydraulicStorageInitial_mol_m2;


if ...
        ~isfinite(hydraulicStorageInitial) ...
        || hydraulicStorageInitial <= 0

    error( ...
        'Initial hydraulic storage amount must be positive.');

end


if ~isfield(hydro,'hydraulicStorageAmount_mol_m2')

    error( ...
        'hydro.hydraulicStorageAmount_mol_m2 is required.');

end


hydraulicStorageAmount = ...
    hydro.hydraulicStorageAmount_mol_m2(:);


if numel(hydraulicStorageAmount) ~= nT

    error([ ...
        'hydro.hydraulicStorageAmount_mol_m2 must match ' ...
        'timeDays.']);

end


if any(~isfinite(hydraulicStorageAmount))

    error( ...
        'Hydraulic storage contains non-finite values.');

end


if any(hydraulicStorageAmount <= 0)

    error([ ...
        'Hydraulic storage became non-positive. ' ...
        'Minimum storage = %.3f mol m^-2.'], ...
        min(hydraulicStorageAmount));

end

storageComponentResidual = ...
    hydraulicStorageAmount ...
    - storageLumenAmount ...
    - storageLivingAmount;


releaseComponentResidual = ...
    Jrelease ...
    - JreleaseLumen ...
    - JreleaseLiving;


rechargeComponentResidual = ...
    Jrecharge ...
    - JrechargeLumen ...
    - JrechargeLiving;


if max(abs(storageComponentResidual),[],'omitnan') > 1e-8

    error( ...
        'Lumen + living storage do not reproduce total storage.');

end


if ...
        max(abs(releaseComponentResidual),[],'omitnan') > 1e-10 ...
        || max(abs(rechargeComponentResidual),[],'omitnan') > 1e-10

    error( ...
        'Component hydraulic storage fluxes do not reproduce totals.');

end

%% ========================================================================
% Storage distribution among mobile segments
% ========================================================================

if isfield(traits,'storageDistributionWeights')

    storageWeights = ...
        traits.storageDistributionWeights(:);


    if numel(storageWeights) ~= nMobile

        error([ ...
            'storageDistributionWeights must have ' ...
            'nMobileTanks elements.']);

    end


    if ...
            any(~isfinite(storageWeights)) ...
            || any(storageWeights <= 0) ...
            || sum(storageWeights) <= 0

        error([ ...
            'storageDistributionWeights must contain one positive ' ...
            'weight for every mobile tank.']);

    end


    storageWeights = ...
        storageWeights ...
        ./ sum(storageWeights);

else

    storageWeights = ...
        ones(nMobile,1) ...
        ./ nMobile;

end




%% ========================================================================
% Component-specific gross storage exchange
% ========================================================================

if isfield(traits,'storageLumenExchangeTauDays')

    storageLumenExchangeTauDays = ...
        traits.storageLumenExchangeTauDays;

else

    error( ...
        'A lumen storage-exchange timescale is required.');

end


if isfield(traits,'storageLivingExchangeTauDays')

    storageLivingExchangeTauDays = ...
        traits.storageLivingExchangeTauDays;

elseif isfield(traits,'storageExchangeTauDays')

    storageLivingExchangeTauDays = ...
        traits.storageExchangeTauDays;

else

    error( ...
        'A living-storage exchange timescale is required.');

end


if ...
        ~isfinite(storageLumenExchangeTauDays) ...
        || storageLumenExchangeTauDays <= 0

    error( ...
        'storageLumenExchangeTauDays must be positive.');

end


if ...
        ~isfinite(storageLivingExchangeTauDays) ...
        || storageLivingExchangeTauDays <= 0

    error( ...
        'storageLivingExchangeTauDays must be positive.');

end

if ...
        storageLumenExchangeTauDays > 1e4 ...
        && ~isfield(traits,'storageLumenInitialAgeDays') ...
        && ~isfield(traits,'storageInitialAgeDays')

    warning([ ...
        'Very long lumen exchange timescale is also being used ' ...
        'to initialize lumen storage age. Supply an explicit ' ...
        'storageLumenInitialAgeDays for near-zero-exchange tests.']);

end


%% ========================================================================
% Initial isotope states: exact D-atom inventories
% ========================================================================

rRoot = ...
    delta2ratio(dRoot);


xRoot = ...
    normalizedRatioToAtomFraction( ...
        rRoot, ...
        Rstandard_DH);


r0 = ...
    rRoot(1);


x0 = ...
    xRoot(1);


%% ------------------------------------------------------------------------
% Fast mobile-only and full mobile initial states
% -------------------------------------------------------------------------

NDfast0 = ...
    2 ...
    .* mobileWaterSegment ...
    .* repmat( ...
        x0, ...
        nMobile, ...
        1);


NDmobile0 = ...
    NDfast0;


%% ------------------------------------------------------------------------
% Initial isotope composition of the two storage pools
% -------------------------------------------------------------------------

if isfield(traits,'storageLumenInitialDeltaD')

    rLumen0 = ...
        delta2ratio( ...
            traits.storageLumenInitialDeltaD);

elseif isfield(traits,'storageInitialDeltaD')

    rLumen0 = ...
        delta2ratio( ...
            traits.storageInitialDeltaD);

else

    rLumen0 = ...
        r0;

end


if isfield(traits,'storageLivingInitialDeltaD')

    rLiving0 = ...
        delta2ratio( ...
            traits.storageLivingInitialDeltaD);

elseif isfield(traits,'storageInitialDeltaD')

    rLiving0 = ...
        delta2ratio( ...
            traits.storageInitialDeltaD);

else

    rLiving0 = ...
        r0;

end


if ...
        ~isscalar(rLumen0) ...
        || ~isscalar(rLiving0)

    error( ...
        'Initial storage isotope values must currently be scalar.');

end


xLumen0 = ...
    normalizedRatioToAtomFraction( ...
        rLumen0, ...
        Rstandard_DH);


xLiving0 = ...
    normalizedRatioToAtomFraction( ...
        rLiving0, ...
        Rstandard_DH);


storageLumenSegment0 = ...
    storageWeights ...
    .* storageLumenAmount(1);


storageLivingSegment0 = ...
    storageWeights ...
    .* storageLivingAmount(1);


NDLumen0 = ...
    2 ...
    .* storageLumenSegment0 ...
    .* xLumen0;


NDLiving0 = ...
    2 ...
    .* storageLivingSegment0 ...
    .* xLiving0;

%% ========================================================================
% Initial water ages
% ========================================================================

tauMobileSegment0 = ...
    mobileWaterSegment ...
    ./ JrefDay;


Afast0 = ...
    (1:nMobile)' ...
    .* tauMobileSegment0;


Amobile0 = ...
    Afast0;


%% ------------------------------------------------------------------------
% Initial storage ages
% -------------------------------------------------------------------------

if isfield(traits,'storageLumenInitialAgeDays')

    if isscalar(traits.storageLumenInitialAgeDays)

        ALumen0 = ...
            repmat( ...
                traits.storageLumenInitialAgeDays, ...
                nMobile,1);

    else

        ALumen0 = ...
            traits.storageLumenInitialAgeDays(:);

    end

elseif isfield(traits,'storageInitialAgeDays')

    if isscalar(traits.storageInitialAgeDays)

        ALumen0 = ...
            repmat( ...
                traits.storageInitialAgeDays, ...
                nMobile,1);

    else

        ALumen0 = ...
            traits.storageInitialAgeDays(:);

    end

else

    ALumen0 = ...
        Amobile0 ...
        + storageLumenExchangeTauDays;

end


if isfield(traits,'storageLivingInitialAgeDays')

    if isscalar(traits.storageLivingInitialAgeDays)

        ALiving0 = ...
            repmat( ...
                traits.storageLivingInitialAgeDays, ...
                nMobile,1);

    else

        ALiving0 = ...
            traits.storageLivingInitialAgeDays(:);

    end

elseif isfield(traits,'storageInitialAgeDays')

    if isscalar(traits.storageInitialAgeDays)

        ALiving0 = ...
            repmat( ...
                traits.storageInitialAgeDays, ...
                nMobile,1);

    else

        ALiving0 = ...
            traits.storageInitialAgeDays(:);

    end

else

    ALiving0 = ...
        Amobile0 ...
        + storageLivingExchangeTauDays;

end


if ...
        numel(ALumen0) ~= nMobile ...
        || numel(ALiving0) ~= nMobile

    error( ...
        'Initial component storage ages must match nMobileTanks.');

end

GLumen0 = ...
    storageLumenSegment0 ...
    .* ALumen0;


GLiving0 = ...
    storageLivingSegment0 ...
    .* ALiving0;

%% ========================================================================
% State vector
%
% Exact isotope states are D-atom inventories:
%
%   ND = 2 * W * xD
%
% 1             : N       NDfast
% N+1           : 2N      NDmobile
% 2N+1          : 3N      ND lumen storage
% 3N+1          : 4N      ND living storage
% 4N+1          : 5N      Afast
% 5N+1          : 6N      Amobile
% 6N+1          : 7N      age inventory, lumen storage
% 7N+1          : 8N      age inventory, living storage
% 8N+1                    cumulative external D input
% 8N+2                    cumulative external D output
% 8N+3                    cumulative legacy normalized-ratio input
% 8N+4                    cumulative legacy normalized-ratio output
% ========================================================================

boundaryInputD0 = ...
    0;


boundaryOutputD0 = ...
    0;


boundaryInputRatio0 = ...
    0;


boundaryOutputRatio0 = ...
    0;


y0 = [ ...
    NDfast0; ...
    NDmobile0; ...
    NDLumen0; ...
    NDLiving0; ...
    Afast0; ...
    Amobile0; ...
    GLumen0; ...
    GLiving0; ...
    boundaryInputD0; ...
    boundaryOutputD0; ...
    boundaryInputRatio0; ...
    boundaryOutputRatio0];


%% ========================================================================
% Interval-wise integration
% ========================================================================

dtForcing = ...
    min(diff(t));


nState = ...
    numel(y0);


Y = ...
    NaN(nT,nState);


Y(1,:) = ...
    y0.';


for k = 1:nT-1

    tk = ...
        t(k);


    tk1 = ...
        t(k+1);


    dtInterval = ...
        tk1 ...
        - tk;


    interval = ...
        struct;


    interval.t0 = ...
        tk;


    interval.t1 = ...
        tk1;


    interval.rRoot0 = ...
        rRoot(k);


    interval.rRoot1 = ...
        rRoot(k+1);


    interval.rootIsotopeInterpolation = ...
        rootIsotopeInterpolation;

    interval.throughflowToleranceDay = ...
        throughflowTolerance .* secondsPerDay;

    interval.JrootDay = ...
        max(Jroot(k+1),0) ...
        .* secondsPerDay;


    interval.JreleaseLumenDay = ...
        max(JreleaseLumen(k+1),0) ...
        .* secondsPerDay;


    interval.JrechargeLumenDay = ...
        max(JrechargeLumen(k+1),0) ...
        .* secondsPerDay;


    interval.JreleaseLivingDay = ...
        max(JreleaseLiving(k+1),0) ...
        .* secondsPerDay;


    interval.JrechargeLivingDay = ...
        max(JrechargeLiving(k+1),0) ...
        .* secondsPerDay;


    interval.storageLumenStart = ...
        storageLumenAmount(k);


    interval.storageLumenEnd = ...
        storageLumenAmount(k+1);


    interval.storageLivingStart = ...
        storageLivingAmount(k);


    interval.storageLivingEnd = ...
        storageLivingAmount(k+1);


    optsInterval = ...
        odeset( ...
            'RelTol', ...
            odeRelTol, ...
            'AbsTol', ...
            odeAbsTol, ...
            'MaxStep', ...
            dtInterval ...
            .* odeMaxStepFraction);


    rhs = ...
        @(tt,y) xylemCoupledRHSExactDInterval( ...
            tt, ...
            y, ...
            interval, ...
            storageWeights, ...
            mobileWaterSegment, ...
            storageLumenExchangeTauDays, ...
            storageLivingExchangeTauDays, ...
            nMobile, ...
            Rstandard_DH);


    [~,Yinterval] = ...
        ode15s( ...
            rhs, ...
