%% =========================================================================
function dydt = xylemCoupledRHSExactDInterval( ...
    tt, ...
    y, ...
    interval, ...
    storageWeights, ...
    mobileWaterSegment, ...
    storageLumenExchangeTauDays, ...
    storageLivingExchangeTauDays, ...
    nMobile, ...
    Rstandard_DH)
%XYLEMCOUPLEDRHSEXACTDINTERVAL



%% ------------------------------------------------------------------------
% Unpack exact-D and age states
% -------------------------------------------------------------------------

NDf = ...
    y(1:nMobile);


NDm = ...
    y( ...
        nMobile+1 : 2*nMobile);


NDL = ...
    y( ...
        2*nMobile+1 : 3*nMobile);


NDE = ...
    y( ...
        3*nMobile+1 : 4*nMobile);


Af = ...
    y( ...
        4*nMobile+1 : 5*nMobile);


Am = ...
    y( ...
        5*nMobile+1 : 6*nMobile);


GL = ...
    y( ...
        6*nMobile+1 : 7*nMobile);


GE = ...
    y( ...
        7*nMobile+1 : 8*nMobile);


%% ------------------------------------------------------------------------
% Position within interval
% -------------------------------------------------------------------------

if interval.t1 > interval.t0

    f = ...
        (tt - interval.t0) ...
        ./ (interval.t1 - interval.t0);

else

    f = ...
        1;

end


f = ...
    min(max(f,0),1);


%% ------------------------------------------------------------------------
% Root isotope forcing
% -------------------------------------------------------------------------

if interval.rootIsotopeInterpolation == "next"

    rIn = ...
        interval.rRoot1;

else

    rIn = ...
        interval.rRoot0 ...
        + f ...
        .* ( ...
            interval.rRoot1 ...
            - interval.rRoot0);

end


xIn = ...
    normalizedRatioToAtomFraction( ...
        rIn, ...
        Rstandard_DH);


%% ------------------------------------------------------------------------
% Hydraulic rates for this interval, mol m^-2 day^-1
% -------------------------------------------------------------------------

Jr = ...
    interval.JrootDay;


JLrelTotal = ...
    interval.JreleaseLumenDay;


JLrechTotal = ...
    interval.JrechargeLumenDay;


JErelTotal = ...
    interval.JreleaseLivingDay;


JErechTotal = ...
    interval.JrechargeLivingDay;


%% ------------------------------------------------------------------------
% Storage amounts vary linearly between accepted hydraulic nodes
% -------------------------------------------------------------------------

SLtotal = ...
    interval.storageLumenStart ...
    + f ...
    .* ( ...
        interval.storageLumenEnd ...
        - interval.storageLumenStart);


SEtotal = ...
    interval.storageLivingStart ...
    + f ...
    .* ( ...
        interval.storageLivingEnd ...
        - interval.storageLivingStart);


SLtotal = ...
    max(SLtotal,0);


SEtotal = ...
    max(SEtotal,0);


storageWeightsLocal = ...
    storageWeights(:);


SL = ...
    storageWeightsLocal ...
    .* SLtotal;


SE = ...
    storageWeightsLocal ...
    .* SEtotal;


JLrel = ...
    storageWeightsLocal ...
    .* JLrelTotal;


JLrech = ...
    storageWeightsLocal ...
    .* JLrechTotal;


JErel = ...
    storageWeightsLocal ...
    .* JErelTotal;


JErech = ...
    storageWeightsLocal ...
    .* JErechTotal;


%% ------------------------------------------------------------------------
% Gross bidirectional exchange
% -------------------------------------------------------------------------

JexchangeL = ...
    SL ...
    ./ storageLumenExchangeTauDays;


JexchangeE = ...
    SE ...
    ./ storageLivingExchangeTauDays;


%% ------------------------------------------------------------------------
% Recover isotope atom fractions from exact D inventories
% -------------------------------------------------------------------------

xF = ...
    NDf ...
    ./ (2 .* mobileWaterSegment);


xM = ...
    NDm ...
    ./ (2 .* mobileWaterSegment);


xL = ...
    xM;


xE = ...
    xM;


storageTol = ...
    1e-12;


validL = ...
    SL > storageTol;


validE = ...
    SE > storageTol;


xL(validL) = ...
    NDL(validL) ...
    ./ (2 .* SL(validL));


xE(validE) = ...
    NDE(validE) ...
    ./ (2 .* SE(validE));


%% ------------------------------------------------------------------------
% Recover storage ages from age inventories
% -------------------------------------------------------------------------

AL = ...
    Am;


AE = ...
    Am;


AL(validL) = ...
    GL(validL) ...
    ./ SL(validL);


AE(validE) = ...
    GE(validE) ...
    ./ SE(validE);


%% ------------------------------------------------------------------------
% Mobile throughflow
% -------------------------------------------------------------------------

Jin = ...
    zeros(nMobile,1);


Jout = ...
    zeros(nMobile,1);


Jin(1) = ...
    Jr;


throughflowToleranceDay = ...
    interval.throughflowToleranceDay;


for j = 1:nMobile

    JoutRaw = ...
        Jin(j) ...
        + JLrel(j) ...
        + JErel(j) ...
        - JLrech(j) ...
        - JErech(j);


    if JoutRaw < -throughflowToleranceDay

        error( ...
            ['Exact-D xylem interval produced materially negative ' ...
             'mobile throughflow at t = %.12g d, segment %d: ' ...
             '%.12g mol m^-2 day^-1.'], ...
            tt, ...
            j, ...
            JoutRaw);

    end


    Jout(j) = ...
        max(JoutRaw,0);


    if j < nMobile

        Jin(j+1) = ...
            Jout(j);

    end

end


%% ------------------------------------------------------------------------
% Allocate derivatives
% -------------------------------------------------------------------------

dNDf = ...
    zeros(nMobile,1);


dNDm = ...
    zeros(nMobile,1);


dNDL = ...
    zeros(nMobile,1);


dNDE = ...
    zeros(nMobile,1);


dAf = ...
    zeros(nMobile,1);


dAm = ...
    zeros(nMobile,1);


dGL = ...
    zeros(nMobile,1);


dGE = ...
    zeros(nMobile,1);


%% ========================================================================
% Fast mobile-only reference
% ========================================================================

for j = 1:nMobile

    if j == 1

        xSourceFast = ...
            xIn;

        AsourceFast = ...
            0;

    else

        xSourceFast = ...
            xF(j-1);

        AsourceFast = ...
            Af(j-1);

    end


    dNDf(j) = ...
        2 ...
        .* Jr ...
        .* ( ...
            xSourceFast ...
            - xF(j));


    kFast = ...
        Jr ...
        ./ mobileWaterSegment;


    dAf(j) = ...
        1 ...
        + kFast ...
        .* ( ...
            AsourceFast ...
            - Af(j));

end


%% ========================================================================
% Coupled mobile + lumen + living storage
% ========================================================================

for j = 1:nMobile

    if j == 1

        xUpstream = ...
            xIn;

        Aupstream = ...
            0;

    else

        xUpstream = ...
            xM(j-1);

        Aupstream = ...
            Am(j-1);

    end


    %% ------------------------------------------------------------
    % Exact D inventory of constant-volume mobile segment
    % -------------------------------------------------------------

    dNDm(j) = ...
        2 ...
        .* ( ...
            Jin(j) .* xUpstream ...
            + (JexchangeL(j) + JLrel(j)) .* xL(j) ...
            + (JexchangeE(j) + JErel(j)) .* xE(j) ...
            - ( ...
                Jout(j) ...
                + JLrech(j) ...
                + JErech(j) ...
                + JexchangeL(j) ...
                + JexchangeE(j)) .* xM(j));


    %% ------------------------------------------------------------
    % Exact D inventory of lumen storage
    % -------------------------------------------------------------

    dNDL(j) = ...
        2 ...
        .* ( ...
            JLrech(j) .* xM(j) ...
            - JLrel(j) .* xL(j) ...
            + JexchangeL(j) .* (xM(j)-xL(j)));


    %% ------------------------------------------------------------
    % Exact D inventory of living storage
    % -------------------------------------------------------------

    dNDE(j) = ...
        2 ...
        .* ( ...
            JErech(j) .* xM(j) ...
            - JErel(j) .* xE(j) ...
            + JexchangeE(j) .* (xM(j)-xE(j)));


    %% ------------------------------------------------------------
    % Mobile age
    % -------------------------------------------------------------

    kAdv = ...
        Jin(j) ...
        ./ mobileWaterSegment;


    kLumenToMobile = ...
        ( ...
            JexchangeL(j) ...
            + JLrel(j)) ...
        ./ mobileWaterSegment;


    kLivingToMobile = ...
        ( ...
            JexchangeE(j) ...
            + JErel(j)) ...
        ./ mobileWaterSegment;


    dAm(j) = ...
        1 ...
        + kAdv .* (Aupstream-Am(j)) ...
        + kLumenToMobile .* (AL(j)-Am(j)) ...
        + kLivingToMobile .* (AE(j)-Am(j));


    %% ------------------------------------------------------------
    % Storage age inventories
    % -------------------------------------------------------------

    dGL(j) = ...
        SL(j) ...
        + JLrech(j) .* Am(j) ...
        - JLrel(j) .* AL(j) ...
        + JexchangeL(j) .* (Am(j)-AL(j));


    dGE(j) = ...
        SE(j) ...
        + JErech(j) .* Am(j) ...
        - JErel(j) .* AE(j) ...
        + JexchangeE(j) .* (Am(j)-AE(j));

end


%% ------------------------------------------------------------------------
% External inventory fluxes
% -------------------------------------------------------------------------

xTerminal = ...
    xM(end);


RinAbsolute = ...
    Rstandard_DH ...
    .* rIn;


RterminalAbsolute = ...
    xTerminal ...
    ./ (1-xTerminal);


rTerminal = ...
    RterminalAbsolute ...
    ./ Rstandard_DH;


dBoundaryInputD = ...
    2 ...
    .* Jr ...
    .* xIn;


dBoundaryOutputD = ...
    2 ...
    .* Jout(end) ...
    .* xTerminal;


dBoundaryInputRatio = ...
    Jr ...
    .* ( ...
        RinAbsolute ...
        ./ Rstandard_DH);


dBoundaryOutputRatio = ...
    Jout(end) ...
    .* rTerminal;


%% ------------------------------------------------------------------------
% Pack
% -------------------------------------------------------------------------

dydt = [ ...
    dNDf; ...
    dNDm; ...
    dNDL; ...
    dNDE; ...
    dAf; ...
    dAm; ...
    dGL; ...
    dGE; ...
    dBoundaryInputD; ...
    dBoundaryOutputD; ...
    dBoundaryInputRatio; ...
    dBoundaryOutputRatio];

end


%% =========================================================================
function x = normalizedRatioToAtomFraction(r,Rstd)
%NORMALIZEDRATIOTOATOMFRACTION
%
% r = R/Rstd, where R = D/H.

R = ...
    Rstd ...
    .* r;


x = ...
    R ...
    ./ (1 + R);

end


%% =========================================================================
function r = exactDInventoryToNormalizedRatio(ND,W,Rstd)
%EXACTDINVENTORYTONORMALIZEDRATIO
%
% Convert exact D atoms in a water inventory back to R/Rstd.

x = ...
    ND ...
    ./ (2 .* W);


if any(~isfinite(x),'all')

    error( ...
        'Nonfinite D atom fraction while reconstructing xylem isotope state.');

end


if any(x < -1e-12 | x >= 1+1e-12,'all')

    error( ...
        'Invalid D atom fraction while reconstructing xylem isotope state.');

end


x = ...
    min(max(x,0),1-eps);


R = ...
    x ...
    ./ (1-x);


r = ...
    R ...
    ./ Rstd;

end


function alpha = parse_xylem_isotope_selectivity(traits)
%PARSE_XYLEM_ISOTOPE_SELECTIVITY
%
% Fractionation/selectivity hooks for xylem water transfer.
%
% All are fixed at unity in the current validated implementation.


alpha.rootToMobile = ...
    1;


alpha.axialMobile = ...
    1;


alpha.mobileToLumen = ...
    1;


alpha.lumenToMobile = ...
    1;


alpha.mobileToLiving = ...
    1;


alpha.livingToMobile = ...
    1;


%% ------------------------------------------------------------------------
% Optional user-supplied structure
% -------------------------------------------------------------------------

if isfield(traits,'isotopeSelectivity')

    supplied = ...
        traits.isotopeSelectivity;


    names = ...
        fieldnames(alpha);


    for k = 1:numel(names)

        name = ...
            names{k};


        if isfield(supplied,name)

            alpha.(name) = ...
                supplied.(name);

        end

    end

end


%% ------------------------------------------------------------------------
% Validation
% -------------------------------------------------------------------------

names = ...
    fieldnames(alpha);


values = ...
    NaN(size(names));


for k = 1:numel(names)

    value = ...
        alpha.(names{k});


    if ...
            ~isscalar(value) ...
            || ~isfinite(value) ...
            || value <= 0

        error( ...
            'isotopeSelectivity.%s must be a positive scalar.', ...
            names{k});

    end


    values(k) = ...
        value;

end


%% ------------------------------------------------------------------------
% Non-unity selectivity is intentionally disabled for now
% -------------------------------------------------------------------------

if any(abs(values - 1) > 1e-12)

    error([ ...
        'Non-unity xylem isotope selectivity is not yet enabled. ' ...
        'Exact D/H inventory bookkeeping is active in this function, ' ...
        'but isotope-selective transfer equations have not yet been ' ...
        'implemented or validated.']);

end

end




