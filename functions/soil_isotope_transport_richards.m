function I = soil_isotope_transport_richards( ...
    S, ...
    deltaDInitial_permil, ...
    deltaDPrecip_permil, ...
    deltaDRootRelease_permil, ...
    cfg)
%SOIL_ISOTOPE_TRANSPORT_RICHARDS
%
% Conservative D/H transport through a previously solved Richards soil
% trajectory. 
%
%   - precipitation isotope input through infiltration
%   - nonfractionating vertical advective transport
%   - nonfractionating root uptake
%   - root-to-soil hydraulic release with prescribed plant-water deltaD
%   - nonfractionating deep drainage
%
% Internally, isotope conservation uses absolute deuterium-atom inventory:
%
%   N_D = 2 * N_H2O * x_D
%
% where
%
%   x_D = R / (1 + R)
%   R   = Rstd * (1 + deltaD/1000)
%
% The factor 2 accounts for two hydrogen atoms per water molecule.


%% ========================================================================
% Configuration
% ========================================================================

if nargin < 5 || isempty(cfg)

    cfg = ...
        struct;

end


cfg = ...
    setDefault( ...
        cfg, ...
        'Rstandard_DH', ...
        155.76e-6);

cfg = ...
    setDefault( ...
        cfg, ...
        'maxFractionalOutflowPerSubstep', ...
        0.05);

cfg = ...
    setDefault( ...
        cfg, ...
        'minimumSubsteps', ...
        1);

cfg = ...
    setDefault( ...
        cfg, ...
        'maximumSubsteps', ...
        5000);

cfg = ...
    setDefault( ...
        cfg, ...
        'waterTrajectoryTolerance_mol_m2', ...
        1e-8);


Rstd = ...
    cfg.Rstandard_DH;


if ...
        ~isscalar(Rstd) ...
        || ~isfinite(Rstd) ...
        || Rstd <= 0

    error( ...
        'cfg.Rstandard_DH must be a positive finite scalar.');

end


if ...
        cfg.maxFractionalOutflowPerSubstep <= 0 ...
        || cfg.maxFractionalOutflowPerSubstep > 1

    error( ...
        ['cfg.maxFractionalOutflowPerSubstep must lie in ' ...
         '(0,1].']);

end

cfg = ...
    setDefault( ...
        cfg, ...
        'rootReleaseMode', ...
        'mixedRootNode');


rootReleaseMode = ...
    lower(string( ...
        cfg.rootReleaseMode));


if ...
        rootReleaseMode ~= "mixedrootnode" ...
        && rootReleaseMode ~= "prescribed"

    error([ ...
        'cfg.rootReleaseMode must be either ' ...
        '"mixedRootNode" or "prescribed".']);

end


%% ========================================================================
% Hydraulic dimensions and exact coarse-interval transfers
% ========================================================================

W_hydro = ...
    S.waterAmount_mol_m2;

[nCell,nT] = ...
    size(W_hydro);

nInt = ...
    nT - 1;


if nInt < 1

    error( ...
        'Richards trajectory must contain at least two time nodes.');

end


T = ...
    reconstruct_richards_interval_transfers(S);


%% ========================================================================
% Expand isotope forcings
% ========================================================================

deltaInitial = ...
    expandInitialDelta( ...
        deltaDInitial_permil, ...
        nCell, ...
        S);


deltaPrecip = ...
    expandIntervalDelta( ...
        deltaDPrecip_permil, ...
        1, ...
        nInt, ...
        nT, ...
        'deltaDPrecip_permil');


rootSigned = ...
    T.rootTransferSigned_mol_m2;


hasRelease = ...
    any(rootSigned < 0,'all');


if hasRelease

    switch rootReleaseMode

        case "prescribed"

            if nargin < 4 || isempty(deltaDRootRelease_permil)

                error([ ...
                    'Negative root flux is present and ' ...
                    'cfg.rootReleaseMode = "prescribed". ' ...
                    'deltaDRootRelease_permil must therefore ' ...
                    'be supplied.']);

            end


            deltaRootRelease = ...
                expandRootReleaseDelta( ...
                    deltaDRootRelease_permil, ...
                    nCell, ...
                    nInt, ...
                    nT);


            missingRelease = ...
                rootSigned < 0 ...
                & ~isfinite(deltaRootRelease);


            if any(missingRelease,'all')

                error([ ...
                    'Nonfinite prescribed root-release isotope ' ...
                    'composition occurs where root-to-soil ' ...
                    'hydraulic release is nonzero.']);

            end


        case "mixedrootnode"

            % Release composition is calculated dynamically from the
            % instantaneous gross soil-to-root isotope mixture.

            deltaRootRelease = ...
                NaN(nCell,nInt);

    end

else

    deltaRootRelease = ...
        NaN(nCell,nInt);

end


if any(~isfinite(deltaInitial))

    error( ...
        'Initial soil isotope composition contains nonfinite values.');

end


if any( ...
        ~isfinite(deltaPrecip) ...
        & T.infiltration_mol_m2 > 0)

    error( ...
        ['Nonfinite precipitation isotope composition occurs during ' ...
         'nonzero infiltration.']);

end


%% ========================================================================
% Initial isotope state
% ========================================================================

xInitial = ...
    deltaToAtomFraction( ...
        deltaInitial, ...
        Rstd);


ND = ...
    NaN(nCell,nT);

xD = ...
    NaN(nCell,nT);

deltaD = ...
    NaN(nCell,nT);


ND(:,1) = ...
    2 ...
    .* W_hydro(:,1) ...
    .* xInitial;

xD(:,1) = ...
    xInitial;


deltaD(:,1) = ...
    deltaInitial;


%% ========================================================================
% Ledger allocation
% ========================================================================

precipD = ...
    zeros(1,nInt);

rootUptakeWater = ...
    zeros(nCell,nInt);

rootReleaseWater = ...
    zeros(nCell,nInt);

rootUptakeD = ...
    zeros(nCell,nInt);

rootReleaseD = ...
    zeros(nCell,nInt);

interfaceDNet = ...
    zeros(max(nCell-1,0),nInt);

deepWater = ...
    T.deepReconstructed_mol_m2;

deepD = ...
    zeros(1,nInt);

stepDResidual = ...
    zeros(1,nInt);

cumulativeDResidual = ...
    zeros(1,nInt);

waterTrajectoryResidual = ...
    zeros(nCell,nInt);

nIsotopeSubsteps = ...
    zeros(1,nInt);


%% ========================================================================
% Time integration
% ========================================================================

cumulativeResidual = ...
    0;


for k = 1:nInt

    Wstart = ...
        W_hydro(:,k);

    Wtarget = ...
        W_hydro(:,k+1);

    NDwork = ...
        ND(:,k);

    Wwork = ...
        Wstart;


    infiltration = ...
        T.infiltration_mol_m2(k);

    faceNet = ...
        T.interfaceTransferNet_mol_m2(:,k);

    rootNet = ...
        rootSigned(:,k);

    deep = ...
        deepWater(k);


    if deep < -1e-12

        error( ...
            'Reconstructed deep drainage is negative in interval %d.', ...
            k);

    end


    deep = ...
        max(deep,0);


    %% --------------------------------------------------------------------
    % Determine isotope-only subcycling from total donor outflow.
    % ---------------------------------------------------------------------

    totalOut = ...
        max(rootNet,0);


    for f = 1:nCell-1

        if faceNet(f) >= 0

            totalOut(f) = ...
                totalOut(f) ...
                + faceNet(f);

        else

            totalOut(f+1) = ...
                totalOut(f+1) ...
                - faceNet(f);

        end

    end


    totalOut(end) = ...
        totalOut(end) ...
        + deep;


    referenceWater = ...
        max( ...
            min(Wstart,Wtarget), ...
            1e-12);


    maximumTurnover = ...
        max( ...
            totalOut ...
            ./ referenceWater);


    nSub = ...
        max( ...
            cfg.minimumSubsteps, ...
            ceil( ...
                maximumTurnover ...
                ./ cfg.maxFractionalOutflowPerSubstep));


    if nSub > cfg.maximumSubsteps

        error([ ...
            'Isotope transport requires %d substeps in interval %d, ' ...
            'exceeding cfg.maximumSubsteps.'], ...
            nSub, ...
            k);

    end


    nIsotopeSubsteps(k) = ...
        nSub;


    %% --------------------------------------------------------------------
    % Interval isotope forcing
    % ---------------------------------------------------------------------

    if infiltration > 0

        xPrecip = ...
            deltaToAtomFraction( ...
                deltaPrecip(k), ...
                Rstd);

    else

        xPrecip = ...
            NaN;

    end


    if ...
            hasRelease ...
            && rootReleaseMode == "prescribed"

        xReleasePrescribed = ...
            deltaToAtomFraction( ...
            deltaRootRelease(:,k), ...
            Rstd);

    else

        xReleasePrescribed = ...
            NaN(nCell,1);

    end

    %% --------------------------------------------------------------------
    % Conservative isotope substeps
    % ---------------------------------------------------------------------

    for s = 1:nSub

        xNow = ...
            NDwork ...
            ./ ( ...
                2 ...
                .* Wwork);

        %% ------------------------------------------------------------------------
        % Signed root transfer during this isotope substep
        % -------------------------------------------------------------------------

        rootTransferSub = ...
            rootNet ...
            ./ nSub;


        uptakeMask = ...
            rootTransferSub > 0;


        releaseMask = ...
            rootTransferSub < 0;


        %% ------------------------------------------------------------------------
        % Instantaneously mixed common-root isotope composition
        % -------------------------------------------------------------------------

        xRootNode = ...
            NaN;


        grossUptakeSub = ...
            sum( ...
            rootTransferSub(uptakeMask));


        if grossUptakeSub > 0

            xRootNode = ...
                sum( ...
                rootTransferSub(uptakeMask) ...
                .* xNow(uptakeMask)) ...
                ./ grossUptakeSub;

        end


        if ...
                any(releaseMask) ...
                && rootReleaseMode == "mixedrootnode" ...
                && ~isfinite(xRootNode)

            error([ ...
                'Root hydraulic release occurred without a finite ' ...
                'gross-uptake isotope mixture. This is inconsistent ' ...
                'with the current no-root-storage hydraulic topology.']);

        end


        if any(~isfinite(xNow))

            error( ...
                'Nonfinite isotope state in interval %d substep %d.', ...
                k, ...
                s);

        end


        dWstep = ...
            zeros(nCell,1);

        dNDstep = ...
            zeros(nCell,1);


        %% Precipitation / actual infiltration

        dIn = ...
            infiltration ...
            ./ nSub;


        if dIn > 0

            dNDin = ...
                2 ...
                .* dIn ...
                .* xPrecip;


            dWstep(1) = ...
                dWstep(1) ...
                + dIn;

            dNDstep(1) = ...
                dNDstep(1) ...
                + dNDin;

            precipD(k) = ...
                precipD(k) ...
                + dNDin;

        end


        %% Internal vertical advection

        for f = 1:nCell-1

            transfer = ...
                faceNet(f) ...
                ./ nSub;


            if transfer > 0

                donor = ...
                    f;

                receiver = ...
                    f + 1;

                amount = ...
                    transfer;

                signLedger = ...
                    1;

            elseif transfer < 0

                donor = ...
                    f + 1;

                receiver = ...
                    f;

                amount = ...
                    -transfer;

                signLedger = ...
                    -1;

            else

                continue

            end


            dNDtransfer = ...
                2 ...
                .* amount ...
                .* xNow(donor);


            dWstep(donor) = ...
                dWstep(donor) ...
                - amount;

            dWstep(receiver) = ...
                dWstep(receiver) ...
                + amount;

            dNDstep(donor) = ...
                dNDstep(donor) ...
                - dNDtransfer;

            dNDstep(receiver) = ...
                dNDstep(receiver) ...
                + dNDtransfer;


            interfaceDNet(f,k) = ...
                interfaceDNet(f,k) ...
                + signLedger ...
                .* dNDtransfer;

        end


        %% Root uptake and hydraulic release

        for i = 1:nCell

            transfer = ...
                rootNet(i) ...
                ./ nSub;


            if transfer > 0

                % Soil -> root. Nonfractionating removal from donor soil.

                dNDtransfer = ...
                    2 ...
                    .* transfer ...
                    .* xNow(i);


                dWstep(i) = ...
                    dWstep(i) ...
                    - transfer;

                dNDstep(i) = ...
                    dNDstep(i) ...
                    - dNDtransfer;


                rootUptakeWater(i,k) = ...
                    rootUptakeWater(i,k) ...
                    + transfer;

                rootUptakeD(i,k) = ...
                    rootUptakeD(i,k) ...
                    + dNDtransfer;


            elseif transfer < 0

                amount = ...
                    -transfer;


                if rootReleaseMode == "mixedrootnode"

                    xReleaseLocal = ...
                        xRootNode;

                else

                    xReleaseLocal = ...
                        xReleasePrescribed(i);

                end


                dNDtransfer = ...
                    2 ...
                    .* amount ...
                    .* xReleaseLocal;


                dWstep(i) = ...
                    dWstep(i) ...
                    + amount;

                dNDstep(i) = ...
                    dNDstep(i) ...
                    + dNDtransfer;


                rootReleaseWater(i,k) = ...
                    rootReleaseWater(i,k) ...
                    + amount;

                rootReleaseD(i,k) = ...
                    rootReleaseD(i,k) ...
                    + dNDtransfer;

            end

        end


        %% Deep drainage

        dDeep = ...
            deep ...
            ./ nSub;


        if dDeep > 0

            dNDdeep = ...
                2 ...
                .* dDeep ...
                .* xNow(end);


            dWstep(end) = ...
                dWstep(end) ...
                - dDeep;

            dNDstep(end) = ...
                dNDstep(end) ...
                - dNDdeep;


            deepD(k) = ...
                deepD(k) ...
                + dNDdeep;

        end


        %% Apply simultaneous conservative update

        Wnew = ...
            Wwork ...
            + dWstep;

        NDnew = ...
            NDwork ...
            + dNDstep;


        if any(Wnew <= 0)

            error( ...
                ['Isotope transport produced nonpositive soil water ' ...
                 'inventory in interval %d substep %d.'], ...
                k, ...
                s);

        end


        if any(NDnew < -1e-14)

            error( ...
                ['Isotope transport produced negative deuterium ' ...
                 'inventory in interval %d substep %d.'], ...
                k, ...
                s);

        end


        NDnew = ...
            max(NDnew,0);


        Wwork = ...
            Wnew;

        NDwork = ...
            NDnew;

    end


    %% --------------------------------------------------------------------
    % Hydraulic trajectory consistency
    % ---------------------------------------------------------------------

    waterResidual = ...
        Wwork ...
        - Wtarget;


    waterTrajectoryResidual(:,k) = ...
        waterResidual;


    if ...
            max(abs(waterResidual)) ...
            > cfg.waterTrajectoryTolerance_mol_m2

        error([ ...
            'Reconstructed water trajectory differs from Richards ' ...
            'state by %.12g mol m^-2 in interval %d.'], ...
            max(abs(waterResidual)), ...
            k);

    end




    Wwork = ...
        Wtarget;


    %% --------------------------------------------------------------------
    % Store isotope node state
    % ---------------------------------------------------------------------

    ND(:,k+1) = ...
        NDwork;


    xNext = ...
        NDwork ...
        ./ ( ...
            2 ...
            .* Wwork);


    xD(:,k+1) = ...
        xNext;


    deltaD(:,k+1) = ...
        atomFractionToDelta( ...
            xNext, ...
            Rstd);


    %% --------------------------------------------------------------------
    % Whole-column isotope closure
    % ---------------------------------------------------------------------

    actualChange = ...
        sum( ...
            ND(:,k+1) ...
            - ND(:,k));


    predictedChange = ...
        precipD(k) ...
        + sum(rootReleaseD(:,k)) ...
        - sum(rootUptakeD(:,k)) ...
        - deepD(k);


    stepDResidual(k) = ...
        actualChange ...
        - predictedChange;


    cumulativeResidual = ...
        cumulativeResidual ...
        + stepDResidual(k);


    cumulativeDResidual(k) = ...
        cumulativeResidual;

end


%% ========================================================================
% Root-uptake isotope composition
% ========================================================================

rootUptakeWaterTotal = ...
    sum(rootUptakeWater,1);

rootUptakeDTotal = ...
    sum(rootUptakeD,1);

rootUptakeDelta = ...
    NaN(1,nInt);


hasUptake = ...
    rootUptakeWaterTotal > 0;


if any(hasUptake)

    xRootUptake = ...
        rootUptakeDTotal(hasUptake) ...
        ./ ( ...
            2 ...
            .* rootUptakeWaterTotal(hasUptake));


    rootUptakeDelta(hasUptake) = ...
        atomFractionToDelta( ...
            xRootUptake, ...
            Rstd);

end


%% ========================================================================
% Outputs
% ========================================================================

I.timeDays = ...
    S.timeDays;

I.zCenter_m = ...
    S.zCenter_m;

I.zoneIndex = ...
    S.zoneIndex;

I.waterAmount_mol_m2 = ...
    W_hydro;

I.deuteriumAtoms_mol_m2 = ...
    ND;

I.deuteriumAtomFraction = ...
    xD;

I.deltaD_permil = ...
    deltaD;


I.rootUptakeDeltaDInterval_permil = ...
    rootUptakeDelta;

I.rootUptakeWater_mol_m2 = ...
    rootUptakeWater;

I.rootReleaseWater_mol_m2 = ...
    rootReleaseWater;


I.transfer = ...
    T;


I.ledger.precipitationD_mol_m2 = ...
    precipD;

I.ledger.interfaceDNet_mol_m2 = ...
    interfaceDNet;

I.ledger.rootUptakeD_mol_m2 = ...
    rootUptakeD;

I.ledger.rootReleaseD_mol_m2 = ...
    rootReleaseD;

I.ledger.deepDrainageD_mol_m2 = ...
    deepD;


I.processClass.precipitation = ...
    'source/mixing';

I.processClass.verticalAdvection = ...
    'transport/routing';

I.processClass.rootUptake = ...
    'transport/routing; intrinsic alpha = 1';

I.processClass.rootRelease = ...
    'transport/routing from plant reservoir';

I.processClass.deepDrainage = ...
    'transport/routing';

I.processClass.fractionationImplemented = ...
    false;


I.stepIsotopeBalanceResidual_mol_D_m2 = ...
    stepDResidual;

I.cumulativeIsotopeBalanceResidual_mol_D_m2 = ...
    cumulativeDResidual;

I.waterTrajectoryResidual_mol_m2 = ...
    waterTrajectoryResidual;

I.nIsotopeSubsteps = ...
    nIsotopeSubsteps;

I.rootNodeDeltaDInterval_permil = ...
    rootUptakeDelta;


I.rootNodeDefinition = ...
    ['Flux-weighted isotope composition of gross positive ' ...
     'soil-to-root uptake; instantaneous common-root mixing; ' ...
     'no intrinsic root fractionation.'];

rootReleaseWaterTotal = ...
    sum(rootReleaseWater,1);


rootReleaseDTotal = ...
    sum(rootReleaseD,1);


rootAxialWater = ...
    rootUptakeWaterTotal ...
    - rootReleaseWaterTotal;


rootAxialD = ...
    rootUptakeDTotal ...
    - rootReleaseDTotal;


rootAxialDelta = ...
    NaN(1,nInt);


validAxial = ...
    rootAxialWater > 0;


if any(validAxial)

    xAxial = ...
        rootAxialD(validAxial) ...
        ./ ( ...
            2 ...
            .* rootAxialWater(validAxial));


    rootAxialDelta(validAxial) = ...
        atomFractionToDelta( ...
            xAxial, ...
            Rstd);

end


I.rootAxialWater_mol_m2 = ...
    rootAxialWater;


I.rootAxialD_mol_m2 = ...
    rootAxialD;


I.rootAxialDeltaDInterval_permil = ...
    rootAxialDelta;

I.config = ...
    cfg;

end


%% ========================================================================
function delta = expandInitialDelta(deltaInput,nCell,S)

x = ...
    deltaInput(:);


if isscalar(x)

    delta = ...
        repmat(x,nCell,1);

elseif numel(x) == nCell

    delta = ...
        x;

elseif ...
        numel(x) == 3 ...
        && isfield(S,'zoneIndex') ...
        && numel(S.zoneIndex) == nCell

    zone = ...
        S.zoneIndex(:);


    if any(zone < 1 | zone > 3 | zone ~= round(zone))

        error( ...
            'S.zoneIndex is incompatible with three-zone isotope input.');

    end


    delta = ...
        x(zone);

else

    error([ ...
        'deltaDInitial_permil must be scalar, three-zone, or ' ...
        'one value per Richards cell.']);

end

end


%% ========================================================================
function delta = expandIntervalDelta(x,nRow,nInt,nT,name)

if isscalar(x)

    delta = ...
        repmat(x,nRow,nInt);

    return

end


if isvector(x)

    x = ...
        x(:).';


    if numel(x) == nInt

        delta = ...
            repmat(x,nRow,1);

        return

    elseif numel(x) == nT

        delta = ...
            repmat(x(1:nInt),nRow,1);

        return

    end

end


if isequal(size(x),[nRow nInt])

    delta = ...
        x;

elseif isequal(size(x),[nRow nT])

    delta = ...
        x(:,1:nInt);

else

    error( ...
        '%s has incompatible dimensions.', ...
        name);

end

end


%% ========================================================================
function delta = expandRootReleaseDelta(x,nCell,nInt,nT)

if isscalar(x)

    delta = ...
        repmat(x,nCell,nInt);

    return

end


if isvector(x)

    v = ...
        x(:);


    if numel(v) == nCell

        delta = ...
            repmat(v,1,nInt);

        return

    elseif numel(v) == nInt

        delta = ...
            repmat(v.',nCell,1);

        return

    elseif numel(v) == nT

        delta = ...
            repmat(v(1:nInt).',nCell,1);

        return

    end

end


if isequal(size(x),[nCell nInt])

    delta = ...
        x;

elseif isequal(size(x),[nCell nT])

    delta = ...
        x(:,1:nInt);

else

    error([ ...
        'deltaDRootRelease_permil must be scalar, one value per cell, ' ...
        'one value per interval/time node, or an nCell x nInterval ' ...
        'matrix.']);

end

end


%% ========================================================================
function xD = deltaToAtomFraction(delta,Rstd)

R = ...
    Rstd ...
    .* ( ...
        1 ...
        + delta ...
        ./ 1000);


if any(R < 0,'all')

    error( ...
        'deltaD implies a negative D/H ratio.');

end


xD = ...
    R ...
    ./ ( ...
        1 ...
        + R);

end


%% ========================================================================
function delta = atomFractionToDelta(xD,Rstd)

if any(xD < 0 | xD >= 1,'all')

    error( ...
        'Deuterium atom fraction lies outside [0,1).');

end


R = ...
    xD ...
    ./ ( ...
        1 ...
        - xD);


delta = ...
    1000 ...
    .* ( ...
        R ...
        ./ Rstd ...
        - 1);

end


%% ========================================================================
function cfg = setDefault(cfg,name,value)

if ~isfield(cfg,name) || isempty(cfg.(name))

    cfg.(name) = ...
        value;

end

end





